def main():
    # A: серверный модуль
    _, t = load(P_SRV)
    anchor = '\tВозврат ТипЗнч(Значение) = Тип("СправочникСсылка." + ИмяОбъекта);\r\n\r\nКонецФункции\r\n'
    assert t.count(anchor) == 1
    t = t.replace(anchor, anchor + A_SRV.replace("\n", "\r\n"), 1)
    save(P_SRV, t)
    check(True, "A: ВалидироватьСцепку добавлена в Тх_ТехникаСервер")

    # B: ObjectModule документа
    _, t = load(P_DOC)
    hdr_anchor = "//  (г) то же ТС принято в другом подразделении того же сценария -\r\n//      неблокирующее предупреждение (FAQ Q5), проведение проходит.\r\n"
    assert t.count(hdr_anchor) == 1
    t = t.replace(hdr_anchor, hdr_anchor + B_HDR.replace("\n", "\r\n"), 1)
    proc_anchor = "Процедура ОбработкаПроведения(Отказ, РежимПроведения)"
    assert t.count(proc_anchor) == 1
    t = t.replace(proc_anchor, B_PROC.replace("\n", "\r\n") + proc_anchor, 1)
    save(P_DOC, t)
    check(True, "B: ПередЗаписью + ПроверитьСцепкуТабличныхЧастей в ObjectModule")

    # C: Тх_Тесты
    _, t = load(P_TST)
    if not t.endswith("#КонецОбласти\r\n"):
        t = t.rstrip("\r\n") + "\r\n" if not t.endswith("\r\n") else t
    t = t + "\r\n" + C_TEST.replace("\n", "\r\n")
    save(P_TST, t)
    check(True, "C: ТестВалидацииСцепки добавлен в Тх_Тесты")

    # D: раннер
    _, t = load(P_RUN)
    t = t.replace("все 15 тестов", "все 16 тестов")
    call_anchor = "\tЗапуститьТестВалидацииGenericТипов(Результаты);\r\n\r\n\tВозврат Результаты;"
    assert t.count(call_anchor) == 1
    t = t.replace(call_anchor,
                  "\tЗапуститьТестВалидацииGenericТипов(Результаты);\r\n\tЗапуститьТестВалидацииСцепки(Результаты);\r\n\r\n\tВозврат Результаты;", 1)
    tail = "#КонецОбласти\r\n"
    k = t.rfind(tail)
    assert k > 0
    t = t[:k] + D_WRAP.replace("\n", "\r\n") + t[k:]
    save(P_RUN, t)
    check(True, "D: раннер вызывает 16-й тест")

    # E: run_unit_tests.py
    t = P_UT.read_text(encoding="utf-8")
    t = t.replace("all 15 tests", "all 16 tests").replace("expected 15 tests", "expected 16 tests")
    P_UT.write_text(t, encoding="utf-8", newline="")
    check(True, "E: run_unit_tests.py ожидает 16")

    print("RESULT:", "PASS" if ok_all else "FAIL")
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
