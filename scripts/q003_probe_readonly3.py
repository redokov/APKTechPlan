import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client

CONN = "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';"


def q(agent, text, params=None):
    r = agent.NewObject("Запрос")
    r.Текст = text
    if params:
        for k, v in params.items():
            r.УстановитьПараметр(k, v)
    return r.Выполнить().Выгрузить()


def main():
    agent = win32com.client.Dispatch("V85.COMConnector").Connect(CONN)
    print("connected")

    print("\n== A. Полная история дублированной машины (John Deer ВК30-64ВН3)")
    for r in q(agent, """ВЫБРАТЬ
            Ист.Период КАК Период,
            Ист.Организация.Наименование КАК Орг,
            Ист.ЭксплуатирующееПодразделение.Наименование КАК Подр,
            Ист.Исправно КАК Исправно
            ИЗ РегистрСведений.АпкИсторияТранспортныхСредств КАК Ист
            ГДЕ Ист.ТранспортноеСредство.Наименование ПОДОБНО "%ВК30-64ВН3%"
            УПОРЯДОЧИТЬ ПО Ист.Период"""):
        print("   %s | орг=%-10s | подр=%-18s | исправно=%s" % (
            str(r.Период)[:10], r.Орг, r.Подр, r.Исправно))

    print("\n== B. Сколько ТС меняли организацию в истории")
    rows = list(q(agent, """ВЫБРАТЬ
            Ист.ТранспортноеСредство.Наименование КАК ТС,
            КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Ист.Организация) КАК Орг
            ИЗ РегистрСведений.АпкИсторияТранспортныхСредств КАК Ист
            СГРУППИРОВАТЬ ПО Ист.ТранспортноеСредство
            ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Ист.Организация) > 1"""))
    print("   ТС со сменой организации:", len(rows))
    for r in rows[:10]:
        print("     ", r.ТС[:45], "организаций:", r.Орг)

    print("\n== C. Сколько ТС меняли подразделение в истории")
    rows = list(q(agent, """ВЫБРАТЬ
            Ист.ТранспортноеСредство.Наименование КАК ТС,
            КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Ист.ЭксплуатирующееПодразделение) КАК Подр
            ИЗ РегистрСведений.АпкИсторияТранспортныхСредств КАК Ист
            СГРУППИРОВАТЬ ПО Ист.ТранспортноеСредство
            ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Ист.ЭксплуатирующееПодразделение) > 1"""))
    print("   ТС со сменой подразделения:", len(rows))

    print("\n== D. Машины плана без записи истории (нет приписки)")
    rows = list(q(agent, """ВЫБРАТЬ
            ТЧ.ТранспортноеСредство.Наименование КАК ТС
            ИЗ Документ.АпкПланТехническихРесурсов.Техника КАК ТЧ
                ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
                ПО Д.Ссылка = ТЧ.Ссылка
                ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АпкИсторияТранспортныхСредств КАК Ист
                ПО Ист.ТранспортноеСредство = ТЧ.ТранспортноеСредство
            ГДЕ Д.Проведен И Ист.ТранспортноеСредство ЕСТЬ NULL"""))
    print("   машин плана без истории:", len(rows))
    for r in rows[:10]:
        print("     ", r.ТС[:45])

    print("\n== E. Исправность в срезе последних (сколько неисправных среди машин плана)")
    cnt = q(agent, """ВЫБРАТЬ
            ТЧ.ТранспортноеСредство.Наименование КАК ТС,
            Ист.Исправно КАК Исправно
            ИЗ Документ.АпкПланТехническихРесурсов.Техника КАК ТЧ
                ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
                ПО Д.Ссылка = ТЧ.Ссылка
                ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АпкИсторияТранспортныхСредств КАК Ист
                ПО Ист.ТранспортноеСредство = ТЧ.ТранспортноеСредство И Ист.Период = ДАТАВРЕМЯ(2013,12,31)
            ГДЕ Д.Проведен""")
    for r in cnt:
        print("   %-38s исправно=%s" % (r.ТС[:38], r.Исправно))


if __name__ == "__main__":
    main()
