COMMENT_NEW = '''\t// Шаги 1-2 (design §4.7): потребность и доступность - выгрузкой таблиц
\t// значений, один проход по каждой (NFR-002). Дата среза истории ТС -
\t// ДатаНачала запуска (SRV-02 §2); пустая дата внутри ЗапросДоступности
\t// заменяется текущей датой сеанса (решение владельца 10.11.2026).'''


def replace_between(text, start_anchor, end_anchor, new_block, keep_end=True):
    i = text.index(start_anchor)
    j = text.index(end_anchor, i)
    if not keep_end:
        j = j + len(end_anchor)
    old = text[i:j]
    return text[:i] + new_block + text[j:], old


def main():
    with io.open(PATH, encoding="utf-8") as f:
        text = f.read()

    # 1) ЗапросДоступности: от докстринга до докстринга следующей функции
    text, old1 = replace_between(
        text,
        "// Возвращает доступность техники сценария по проведённым документам",
        "// Возвращает суффикс ресурса объёма из параметров с проверкой допустимости",
        ZAPROS_NEW)

    # 2) ДоступныеМоделиПодразделения: от докстринга до строки агрегации
    text, old2 = replace_between(
        text,
        "// документам АпкПланТехническихРесурсов (design 6.2, FR-003.4, TD-007):",
        "\tДля Каждого СтрК Из СтрокиКарты Цикл",
        KARTA_NEW)

    # 3) комментарий в РассчитатьДефицит
    old3 = '''\t// Шаги 1-2 (design §4.7): потребность и доступность - выгрузкой таблиц
\t// значений, один проход по каждой (NFR-002). Дата среза приписки ТС -
\t// ДатаНачала запуска (SRV-02 §2); пустая дата внутри ЗапросДоступности
\t// заменяется самой поздней датой проведённого плана сценария.'''
    assert text.count(old3) == 1, "комментарий РассчитатьДефицит не найден"
    text = text.replace(old3, COMMENT_NEW)

    # проверки
    assert "МАКСИМУМ(Док.Дата)" not in text, "осталась ветка максимума дат планов"
    assert "Документ.АпкПланТехническихРесурсов.Техника КАК Таб" not in text
    assert "Документ.АпкПланТехническихРесурсов.Подразделения КАК Подр" not in text
    assert text.count("Функция ЗапросДоступности") == 1
    assert text.count("Функция ДоступныеМоделиПодразделения") == 1

    with io.open(PATH, "w", encoding="utf-8", newline="") as f:
        f.write(text)

    sys.stdout.buffer.write((
        "OK: ЗапросДоступности (-%d стр), ДоступныеМоделиПодразделения (-%d стр), "
        "комментарий дефицита\n" % (old1.count("\n"), old2.count("\n"))).encode("utf-8"))


if __name__ == "__main__":
    main()
