def check(cond, msg):
    global ok_all
    print(("OK " if cond else "FAIL ") + msg.encode("ascii", "backslashreplace").decode())
    if not cond:
        ok_all = False


def load(p):
    b = p.read_bytes()
    assert b[:3] == b"\xef\xbb\xbf" and b"\r\n" in b
    return b, b[3:].decode("utf-8")


def save(p, text):
    p.write_bytes(b"\xef\xbb\xbf" + text.encode("utf-8"))


