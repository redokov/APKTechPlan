"""Probe: АпкТипТС у ТХТС* после va_prep_data (update-ветка)."""
import sys
import win32com.client

conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';")
q = conn.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ Спр.Код КАК Код, Спр.АпкТипТС = ЗНАЧЕНИЕ(Перечисление.АпкТипыТС.СХТехника) КАК ЭтоСХТехника, "
           "Спр.АпкТипТС = ЗНАЧЕНИЕ(Перечисление.АпкТипыТС.ПустаяСсылка) КАК ТипПуст, Спр.АпкМодель.Наименование КАК Модель "
           "ИЗ Справочник.ТранспортныеСредства КАК Спр ГДЕ Спр.Код ПОДОБНО \"ТХТС%\"")
v = q.Выполнить().Выбрать()
out = sys.stdout.buffer.write
n = 0
while v.Следующий():
    n += 1
    out(("%s СХТехника=%s тип_пуст=%s модель=%s\n" % (v.Код, v.ЭтоСХТехника, v.ТипПуст, v.Модель)).encode("utf-8"))
out(("всего ТХТС*: %d\n" % n).encode("utf-8"))
