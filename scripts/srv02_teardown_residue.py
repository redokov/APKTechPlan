#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""SRV-02 п.6 (Q-006/К4а): teardown-остатки.
04: в конец сценария - удаление приписок и ТС «Тх_VA_04 ТС%»;
08: в финальный серверный блок - удаление созданного плана НИВА/Основной."""
import io
import sys

P04 = "tests/vanessa/04-preduprezhdenie-ts-dva-podrazdeleniya.feature"
P08 = "tests/vanessa/08-formirovanie-plana-rabot-tekhniki.feature"


def main():
    # --- 04: teardown после финального Сообщить
    s = io.open(P04, encoding="utf-8").read()
    anchor = '|Сообщить("ТХ_04 дефицитных строк: " + Строка(ТЗДеф[0].Н) + ", перемещений: " + Строка(ТЗПерем[0].Н));|'
    assert s.count(anchor) == 1
    teardown = '''
\t# 3. Teardown (Q-006/К4а): приписки тестовых ТС убираются набором пустых
\t#    записей, сами ТС удаляются - срез 31.12.1999 и справочник чисты
\t#    для следующих сценариев (зеркало teardown фичи 03).
\tИ я выполняю код встроенного языка на сервере
\t|ЗапросТС = Новый Запрос("ВЫБРАТЬ Спр.Ссылка ИЗ Справочник.ТранспортныеСредства КАК Спр ГДЕ Спр.Наименование ПОДОБНО ""Тх_VA_04 ТС%""");|
\t|ВыбТС = ЗапросТС.Выполнить().Выбрать();|
\t|Пока ВыбТС.Следующий() Цикл|
\t|\tНаборИст = РегистрыСведений.АпкИсторияТранспортныхСредств.СоздатьНаборЗаписей();|
\t|\tНаборИст.Отбор.ТранспортноеСредство.Установить(ВыбТС.Ссылка);|
\t|\tНаборИст.Записать(Истина);|
\t|\tВыбТС.Ссылка.ПолучитьОбъект().Удалить();|
\t|КонецЦикла;|'''
    s = s.replace(anchor, anchor + "\n" + teardown)
    io.open(P04, "w", encoding="utf-8", newline="").write(s)

    # --- 08: удаление созданного плана в финальный блок (после цикла ТХТС)
    s = io.open(P08, encoding="utf-8").read()
    needle = '''\t|\tНаборТХТС.Отбор.ТранспортноеСредство.Установить(ВыбТХТС.Ссылка);|
\t|\tНаборТХТС.Записать(Истина);|
\t|КонецЦикла;|'''
    assert s.count(needle) == 1, s.count(needle)
    add = needle + '''
\t|ЗапросПланов = Новый Запрос("ВЫБРАТЬ С.Ссылка ИЗ Документ.АпкПланТехническихРесурсов КАК С ГДЕ С.Организация.Наименование = ""НИВА"" И С.СценарийПланирования.Наименование = ""Основной""");|
\t|ВыбПланов = ЗапросПланов.Выполнить().Выбрать();|
\t|Пока ВыбПланов.Следующий() Цикл|
\t|\tОбъектПлана = ВыбПланов.Ссылка.ПолучитьОбъект();|
\t|\tЕсли ОбъектПлана.Проведен Тогда ОбъектПлана.Записать(РежимЗаписиДокумента.ОтменаПроведения); КонецЕсли;|
\t|\tОбъектПлана.Удалить();|
\t|КонецЦикла;|'''
    s = s.replace(needle, add)
    io.open(P08, "w", encoding="utf-8", newline="").write(s)

    sys.stdout.buffer.write("OK: 04 teardown + 08 план-teardown\n".encode("utf-8"))


if __name__ == "__main__":
    main()
