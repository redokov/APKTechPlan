def part1_srv_header(srv):
    old = ("//  - автозаполнение коэффициентов пересчёта по мощности"
           " (design §4.6, TD-005).")
    new = ("//  - формирование плана работ: потребность по техкартам"
           " (T7, design 6.1)\n"
           "//    и карта доступных моделей подразделения по документам"
           " АпкПланТехнических\n"
           "//    Ресурсов (T8, design 6.2, FR-003.4).")
    assert srv.count(old) == 1, "часть 1: якорь заголовка не найден"
    return srv.replace(old, new)


def part2_srv_func(srv):
    i = srv.find("#Область ФормированиеПланаРабот")
    assert i >= 0, "часть 2: регион ФормированиеПланаРабот не найден"
    j = srv.find("#КонецОбласти", i)
    assert j > i, "часть 2: конец региона не найден"
    assert "ДоступныеМоделиПодразделения" not in srv, "часть 2: уже применена"
    return srv[:j] + SRV_FUNC.lstrip("\n") + srv[j:]


def part3_tests(tst):
    assert "ТестДоступныеМодели" not in tst, "часть 3: уже применена"
    old = "// Упрощённый xUnit-паттерн: 15 экспортных функций"
    assert tst.count(old) == 1, "часть 3: якорь 15 тестов не найден"
    tst = tst.replace(old, "// Упрощённый xUnit-паттерн: 17 экспортных функций")
    i = tst.find("#Область Тесты_ПотребностьПоТехкартам")
    assert i >= 0, "часть 3: регион Тесты_ПотребностьПоТехкартам не найден"
    j = tst.find("#КонецОбласти", i)
    assert j > i, "часть 3: конец региона не найден"
    end = j + len("#КонецОбласти")
    return tst[:end] + "\n" + TST_FUNC.rstrip("\n") + "\n\n" + tst[end:]


def part4_runner(r):
    assert "ЗапуститьТестДоступныеМодели" not in r, "часть 4: уже применена"
    old_call = "\tЗапуститьТестПотребностьПоТехкартамЧужоеПодразделение(Результаты);"
    assert r.count(old_call) == 1, "часть 4: якорь вызова не найден"
    new_call = (old_call + "\n\tЗапуститьТестДоступныеМоделиПланРаспределения(Результаты);"
                "\n\tЗапуститьТестДоступныеМоделиБезПлана(Результаты);")
    r = r.replace(old_call, new_call)
    old_c = "// Последовательно выполняет все 15 тестов модуля Тх_Тесты и возвращает"
    assert r.count(old_c) == 1, "часть 4: якорь комментария не найден"
    r = r.replace(old_c,
                  "// Последовательно выполняет все 17 тестов модуля Тх_Тесты и возвращает")
    i = r.rfind("#КонецОбласти")
    assert i > 0, "часть 4: конец файла не найден"
    return r[:i] + RUN_WRAP.rstrip("\n") + "\n\n" + r[i:]


def part5_py(u):
    txt = u.read_text(encoding="utf-8")
    assert txt.count("!= 15") == 1 and txt.count("all 15 tests") == 1, \
        f"часть 5: якоря не найдены"
    txt = txt.replace("!= 15", "!= 17").replace("all 15 tests", "all 17 tests")
    u.write_text(txt, encoding="utf-8")


