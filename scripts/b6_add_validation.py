#!/usr/bin/env python3
"""B6 fix: add Тх_ТехникаСервер.ПроверитьЗаписьКоэффициента.

Root cause (probe b6_probe_recordmanager.py): RecordManager.Записать() does
NOT fire the record-set BeforeWrite, and the platform auto record-form is
built on the record manager — so user-editing bypassed FR-003 validation
completely (2nd basic model wrote silently).

Fix: server-side validation by field values (used by the new Тх_ФормаЗаписи
BeforeWrite), returning an array of messages (empty = OK).

Inserts a new region at the end of the module (after the last #КонецОбласти
line), preserving UTF-8 BOM and CRLF.
"""
import io
import sys

MODULE = "src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_ТехникаСервер/Ext/Module.bsl"

CODE = """\r
#Область ВалидацияКоэффициентов\r
\r
// Проверяет коэффициент пересчёта при записи через менеджер записи (форма\r
// записи регистра). B6, 2026-10-09: МенеджерЗаписи.Записать() не вызывает\r
// ПередЗаписью набора записей, платформенная форма записи построена на\r
// менеджере записи — контроль FR-003 в модуле набора при этом обходился\r
// (эмпирика: heartbeat/b6_rmprobe3.txt). Данный метод вызывается из\r
// Тх_ФормаЗаписи.ПередЗаписью и закрывает пользовательский путь записи.\r
// Семантика FR-003: (а) в группе Работа+Период+ВидТехники — не более одной\r
// базовой модели (проверка по базе, текущая модель исключается — её запись\r
// замещает прежнюю строку); (в) коэффициент строго больше нуля;\r
// (г) типы generic-ссылок. Нормализация K=1 у базовой строки выполняется\r
// формой до вызова (FR-003(б)).\r
//\r
// Параметры:\r
//   Работа         - СправочникСсылка - вид работы;\r
//   Период         - Дата - период записи;\r
//   ВидТехники     - ПеречислениеСсылка.Тх_ВидыТехники - вид техники;\r
//   МодельТехники  - СправочникСсылка - модель техники;\r
//   Коэффициент    - Число - коэффициент пересчёта;\r
//   БазоваяМодель  - Булево - признак базовой модели.\r
//\r
// Возвращаемое значение:\r
//   Массив - тексты сообщений об ошибках; пустой массив = запись допустима.\r
//\r
Функция ПроверитьЗаписьКоэффициента(Работа, Период, ВидТехники,\r
\tМодельТехники, Коэффициент, БазоваяМодель) Экспорт\r
\r
\tСообщения = Новый Массив;\r
\r
\tЕсли НЕ ЗначениеЗаполнено(Работа) Тогда\r
\t\tВозврат Сообщения;\r
\tКонецЕсли;\r
\r
\t// FR-003(в): коэффициент строго больше нуля.\r
\tЕсли Коэффициент <= 0 Тогда\r
\t\tСообщения.Добавить("Коэффициент пересчёта должен быть больше нуля.");\r
\tКонецЕсли;\r
\r
\t// FR-003(г): типы generic-ссылок (design 4.1, TD-001).\r
\tЕсли НЕ ВалидироватьТипАПК(Работа, ИмяСправочникаРабот()) Тогда\r
\t\tСообщения.Добавить(\r
\t\t\t"Работа должна быть элементом справочника «ВидыРаботСотрудников».");\r
\tКонецЕсли;\r
\r
\tИмяСправочника = ИмяСправочникаМоделей(ВидТехники);\r
\tЕсли ИмяСправочника <> ""\r
\t\tИ НЕ ВалидироватьТипАПК(МодельТехники, ИмяСправочника) Тогда\r
\t\tСообщения.Добавить("Модель техники не соответствует виду техники.");\r
\tКонецЕсли;\r
\r
\t// FR-003(а): в группе Работа+Период+ВидТехники — одна базовая модель.\r
\t// Текущая модель исключается: её строка замещается записью менеджера.\r
\tЕсли БазоваяМодель Тогда\r
\t\tТекстЗапроса = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК КоличествоБазовых\r
\t\t|ИЗ РегистрСведений.Тх_КоэффициентыПересчетаРабот КАК К\r
\t\t|ГДЕ К.Работа = &Работа\r
\t\t|\tИ К.Период = &Период\r
\t\t|\tИ К.ВидТехники = &ВидТехники\r
\t\t|\tИ К.БазоваяМодель\r
\t\t|\tИ НЕ К.МодельТехники = &МодельТехники";\r
\t\tРезультат = ВыполнитьЗапросАПК(ТекстЗапроса, Новый Структура(\r
\t\t\t"Работа, Период, ВидТехники, МодельТехники",\r
\t\t\tРабота, Период, ВидТехники, МодельТехники));\r
\t\tВыборка = Результат.Выбрать();\r
\t\tЕсли Выборка.Следующий() И Выборка.КоличествоБазовых > 0 Тогда\r
\t\t\tСообщения.Добавить(\r
\t\t\t\t"В наборе записей не может быть двух базовых моделей\r
\t\t\t\t|для одной работы, периода и вида техники.");\r
\t\tКонецЕсли;\r
\tКонецЕсли;\r
\r
\tВозврат Сообщения;\r
\r
КонецФункции\r
\r
#КонецОбласти\r
"""


def main():
    with io.open(MODULE, "r", encoding="utf-8-sig", newline="") as f:
        s = f.read()
    if "ПроверитьЗаписьКоэффициента" in s:
        print("[skip] already present")
        return 0
    marker = "#КонецОбласти"
    pos = s.rfind(marker)
    if pos < 0:
        print("[fail] marker not found")
        return 1
    insert_at = pos + len(marker)
    # newline after marker: keep as is, insert code after it
    s2 = s[:insert_at] + CODE.rstrip("\r") + "\r\n" + s[insert_at:]
    with io.open(MODULE, "w", encoding="utf-8-sig", newline="") as f:
        f.write(s2)
    print("[ok] inserted, new length:", len(s2.splitlines()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
