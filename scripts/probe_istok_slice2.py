#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Probe: распределение периодов/Исправно регистра АпкИсторияТранспортныхСредств, срезы на разные даты,
АпкТипыТС значения + АпкТипТС ТС в срезах. Решает: можно ли изолировать тесты ранней датой среза."""
import sys
import win32com.client

conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';")

def out(s):
    sys.stdout.buffer.write((s + "\n").encode("utf-8"))

def q1(text):
    q = conn.NewObject("Запрос")
    q.Текст = text
    return q.Выполнить().Выбрать()

# 1) min/max период всех записей регистра
v = q1("ВЫБРАТЬ МИНИМУМ(Период) КАК МинП, МАКСИМУМ(Период) КАК МаксП, КОЛИЧЕСТВО(*) КАК Н "
       "ИЗ РегистрСведений.АпкИсторияТранспортныхСредств")
v.Следующий()
out("все записи: Н=%s минПериод=%s максПериод=%s" % (v.Н, v.МинП, v.МаксП))

# 2) срезы на разные даты: сколько ТС и сколько Исправно
for (y, m, d) in [(2014, 1, 1), (2015, 1, 1), (2015, 12, 31), (2026, 1, 1)]:
    v = q1("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н, КОЛИЧЕСТВО(Ист.Исправно) КАК Испр "
           "ИЗ РегистрСведений.АпкИсторияТранспортныхСредств.СрезПоследних(ДАТАВРЕМЯ(%d, %d, %d, 23, 59, 59)) КАК Ист" % (y, m, d))
    v.Следующий()
    out("срез на %04d-%02d-%02d: ТС=%s (КОЛИЧЕСТВО(Исправно)=%s)" % (y, m, d, v.Н, v.Испр))
    v = q1("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н "
           "ИЗ РегистрСведений.АпкИсторияТранспортныхСредств.СрезПоследних(ДАТАВРЕМЯ(%d, %d, %d, 23, 59, 59)) КАК Ист "
           "ГДЕ Ист.Исправно" % (y, m, d))
    v.Следующий()
    out("  из них Исправно=Истина: %s" % v.Н)

# 3) запись регистра с самым ранним периодом
v = q1("ВЫБРАТЬ ПЕРВЫЕ 5 Период, ТранспортноеСредство.Код КАК Код, Исправно "
       "ИЗ РегистрСведений.АпкИсторияТранспортныхСредств УПОРЯДОЧИТЬ ПО Период")
n = 0
while v.Следующий():
    n += 1
    out("ранняя запись: период=%s код=%s исправно=%s" % (v.Период, v.Код, v.Исправно))

# 4) значения перечисления АпкТипыТС (метаданные)
for имя in ["АпкТипыТС"]:
    знч = conn.Перечисления.АпкТипыТС.ПустаяСсылка()
    out("АпкТипыТС пустая: %s" % знч)
    q = conn.NewObject("Запрос")
    q.Текст = ("ВЫБРАТЬ АпкТипыТС.Ссылка КАК Ссылка ИЗ Перечисление.АпкТипыТС КАК АпкТипыТС")
    vv = q.Выполнить().Выбрать()
    while vv.Следующий():
        out("  значение АпкТипыТС: %s" % vv.Ссылка)

# 5) АпкТипТС распределение ТС в срезе на текущую дату
v = q1("ВЫБРАТЬ Ист.ТранспортноеСредство.АпкТипТС КАК Тип, КОЛИЧЕСТВО(*) КАК Н "
       "ИЗ РегистрСведений.АпкИсторияТранспортныхСредств.СрезПоследних(ДАТАВРЕМЯ(2026, 1, 1, 23, 59, 59)) КАК Ист "
       "СГРУППИРОВАТЬ ПО Ист.ТранспортноеСредство.АпкТипТС")
while v.Следующий():
    out("срез 2026 по АпкТипТС: тип=[%s] Н=%s" % (v.Тип, v.Н))

# 6) пустой АпкТипТС и пустая АпкМодель в срезе
v = q1("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н "
       "ИЗ РегистрСведений.АпкИсторияТранспортныхСредств.СрезПоследних(ДАТАВРЕМЯ(2026, 1, 1, 23, 59, 59)) КАК Ист "
       "ГДЕ Ист.Исправно И НЕ Ист.ТранспортноеСредство.АпкТипТС = ЗНАЧЕНИЕ(Перечисление.АпкТипыТС.ПустаяСсылка)")
v.Следующий()
out("исправных с НЕпустым АпкТипТС (срез 2026): %s" % v.Н)
v = q1("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н "
       "ИЗ РегистрСведений.АпкИсторияТранспортныхСредств.СрезПоследних(ДАТАВРЕМЯ(2026, 1, 1, 23, 59, 59)) КАК Ист "
       "ГДЕ Ист.Исправно И Ист.ТранспортноеСредство.АпкМодель = НЕОПРЕДЕЛЕНО")
v.Следующий()
out("исправных с АпкМодель = НЕОПРЕДЕЛЕНО (срез 2026): %s" % v.Н)
