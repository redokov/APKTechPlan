#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Q-003 read-only probe (v2): duplicates of vehicles and attachment period.

Read-only: only Запрос + Выгрузить; nothing is written to the IB.
Aggregation is done by the 1C query language so no COM reference formatting is needed.
"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client

CONN = "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';"
PARTS = ["Техника", "Оборудование", "Автотранспорт", "Прицепы"]


def q(agent, text):
    r = agent.NewObject("Запрос")
    r.Текст = text
    return r.Выполнить().Выгрузить()


def main():
    agent = win32com.client.Dispatch("V85.COMConnector").Connect(CONN)
    print("connected")

    print("\n== 1. Документы плана техресурсов")
    for r in q(agent, """ВЫБРАТЬ
            Д.Номер КАК Номер, Д.Дата КАК Дата, Д.Проведен КАК Проведен,
            Д.СценарийПланирования.Наименование КАК Сценарий,
            Д.Организация.Наименование КАК Организация
            ИЗ Документ.АпкПланТехническихРесурсов КАК Д
            УПОРЯДОЧИТЬ ПО Д.Дата"""):
        print("  %s от %s | проведен=%s | сценарий=%s | орг=%s" % (
            r.Номер, str(r.Дата)[:10], r.Проведен, r.Сценарий, r.Организация))

    print("\n== 2. Строки / разные ТС по частям (все документы)")
    for part in PARTS:
        t = q(agent, """ВЫБРАТЬ
            КОЛИЧЕСТВО(*) КАК Строк,
            КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ТЧ.ТранспортноеСредство) КАК РазныхТС
            ИЗ Документ.АпкПланТехническихРесурсов.%s КАК ТЧ""" % part)
        print("  ТЧ %-14s строк=%-3s разныхТС=%s" % (part, t[0].Строк, t[0].РазныхТС))

    print("\n== 3. Повторы ТС внутри одного документа")
    found = False
    for part in PARTS:
        for r in q(agent, """ВЫБРАТЬ
                Д.Номер КАК Номер,
                ТЧ.ТранспортноеСредство.Наименование КАК ТС,
                КОЛИЧЕСТВО(*) КАК К
                ИЗ Документ.АпкПланТехническихРесурсов.%s КАК ТЧ
                    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
                    ПО Д.Ссылка = ТЧ.Ссылка
                СГРУППИРОВАТЬ ПО Д.Номер, ТЧ.ТранспортноеСредство
                ИМЕЮЩИЕ КОЛИЧЕСТВО(*) > 1""" % part):
            found = True
            print("  ТЧ %-14s документ %s | %s | строк=%s" % (part, r.Номер, r.ТС, r.К))
    if not found:
        print("  повторов внутри документа нет")

    print("\n== 4. ТС в нескольких проведённых документах одного сценария")
    pairs = q(agent, """ВЫБРАТЬ
        Д.СценарийПланирования.Наименование КАК Сценарий,
        ТЧ.ТранспортноеСредство.Наименование КАК ТС,
        КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Д.Ссылка) КАК Документов,
        КОЛИЧЕСТВО(*) КАК Строк
        ИЗ Документ.АпкПланТехническихРесурсов.Техника КАК ТЧ
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
            ПО Д.Ссылка = ТЧ.Ссылка
        ГДЕ Д.Проведен
        СГРУППИРОВАТЬ ПО Д.СценарийПланирования.Наименование, ТЧ.ТранспортноеСредство
        ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Д.Ссылка) > 1
        УПОРЯДОЧИТЬ ПО Строк УБЫВ""")
    seen = 0
    for r in pairs:
        seen += 1
        if seen <= 10:
            print("  %s | %s | документов=%s строк=%s" % (r.Сценарий, r.ТС, r.Документов, r.Строк))
    print("  всего таких пар (сценарий, ТС):", seen)

    print("\n== 5. Приписка: история ТС (периодический регистр, срез)")
    try:
        tot = q(agent, """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К
            ИЗ РегистрСведений.АпкИсторияТранспортныхСредств""")
        print("  записей всего:", tot[0].К)
        multi = q(agent, """ВЫБРАТЬ
            Ист.ТранспортноеСредство.Наименование КАК ТС,
            КОЛИЧЕСТВО(*) КАК Записей,
            МИНИМУМ(Ист.Период) КАК Первая,
            МАКСИМУМ(Ист.Период) КАК Последняя
            ИЗ РегистрСведений.АпкИсторияТранспортныхСредств КАК Ист
            СГРУППИРОВАТЬ ПО Ист.ТранспортноеСредство
            УПОРЯДОЧИТЬ ПО Записей УБЫВ""")
        rows = list(multi)
        print("  разных ТС в истории:", len(rows))
        for r in rows[:10]:
            print("    %-30s записей=%s %s..%s" % (r.ТС, r.Записей, str(r.Первая)[:10], str(r.Последняя)[:10]))
    except Exception as e:
        print("  ошибка:", e)

    print("\n== 6. ТС, у которых приписка менялась (разные подразделения в истории)")
    try:
        chg = q(agent, """ВЫБРАТЬ
            Ист.ТранспортноеСредство.Наименование КАК ТС,
            КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Ист.ЭксплуатирующееПодразделение) КАК Подразделений,
            КОЛИЧЕСТВО(*) КАК Записей
            ИЗ РегистрСведений.АпкИсторияТранспортныхСредств КАК Ист
            СГРУППИРОВАТЬ ПО Ист.ТранспортноеСредство
            ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Ист.ЭксплуатирующееПодразделение) > 1
            УПОРЯДОЧИТЬ ПО Записей УБЫВ""")
        n = 0
        for r in chg:
            n += 1
            if n <= 10:
                print("    %-30s подразделений=%s записей=%s" % (r.ТС, r.Подразделений, r.Записей))
        print("  всего ТС со сменой подразделения:", n)
    except Exception as e:
        print("  ошибка:", e)

    print("\n== 7. ТЧ vs тип модели (согласованность категории)")
    for part in PARTS:
        for r in q(agent, """ВЫБРАТЬ ТИПЗНАЧЕНИЯ(ТС.АпкМодель) КАК ТипМодели, КОЛИЧЕСТВО(*) КАК К
                ИЗ Документ.АпкПланТехническихРесурсов.%s КАК ТЧ
                    ВНУТРЕННЕЕ СОЕДИНЕНИЕ Справочник.ТранспортныеСредства КАК ТС
                    ПО ТС.Ссылка = ТЧ.ТранспортноеСредство
                СГРУППИРОВАТЬ ПО ТИПЗНАЧЕНИЯ(ТС.АпкМодель)""" % part):
            print("  ТЧ %-14s тип=%s строк=%s" % (part, r.ТипМодели, r.К))

    print("\n== 8. Строки ТЧ Подразделения (скольким подразделениям приписан план)")
    for r in q(agent, """ВЫБРАТЬ
            Д.Номер КАК Номер, КОЛИЧЕСТВО(*) КАК Подразделений,
            МАКСИМУМ(Подр.Подразделение.Наименование) КАК Пример
            ИЗ Документ.АпкПланТехническихРесурсов.Подразделения КАК Подр
                ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
                ПО Д.Ссылка = Подр.Ссылка
            СГРУППИРОВАТЬ ПО Д.Номер"""):
        print("  документ %s | подразделений=%s | напр. %s" % (r.Номер, r.Подразделений, r.Пример))


if __name__ == "__main__":
    main()
