#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T9 fix2 (bsl-ls, вторая волна).

 1. UnusedLocalVariable ТекстКомментария (ЗаполнитьТЧПланаРабот) - инлайн.
 2. MissingParameterDescription "ДокументОбъект" (ЗаполнитьТЧПланаРабот) -
    описание после типа («- заполняемый документ»).
 3. MissingParameterDescription «всех параметров» (ПодобратьЗамещение) -
    многострочное описание параметра Модели свёрнуто в одну строку
    (перенос ломал парсинг докстринга).
 4. EmptyCodeBlock / IfElseIfEndsWithElse (тест ЗамещениеПоШирине) -
    два независимых Если вместо Если/ИначеЕсли/Иначе.
"""
import pathlib

SRV = pathlib.Path(
    "src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_ТехникаСервер/Ext/Module.bsl")
TST = pathlib.Path(
    "src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_Тесты/Ext/Module.bsl")

BOM = bytes([0xEF, 0xBB, 0xBF])

OLD_1 = """				ТекстКомментария = СтрШаблон(НСтр("ru = 'замещение: %1, К=%2'"),
					Строка(Стр.МодельТехники), Формат(Подбор.К, "ЧДЦ=3"));
				Если Подбор.К < 1 Тогда
					ТекстКомментария = ТекстКомментарий
						+ НСтр("ru = ' (замена медленнее)'");
				КонецЕсли;
				НовСтр.Комментарий = ТекстКомментарий;"""

NEW_1 = """				НовСтр.Комментарий = СтрШаблон(НСтр("ru = 'замещение: %1, К=%2'"),
					Строка(Стр.МодельТехники), Формат(Подбор.К, "ЧДЦ=3"));
				Если Подбор.К < 1 Тогда
					НовСтр.Комментарий = НовСтр.Комментарий
						+ НСтр("ru = ' (замена медленнее)'");
				КонецЕсли;"""

OLD_2 = "//   * ДокументОбъект - ДокументОбъект.Тх_ПланТехническихРесурсов;"
NEW_2 = ("//   * ДокументОбъект - ДокументОбъект.Тх_ПланТехническихРесурсов -"
         "\n//     заполняемый документ;")

OLD_3 = """//   * Модели         - ТаблицаЗначений - карта доступности (T8:
//                      МодельТехники, ТипТС, ЕдиницДоступно);"""
NEW_3 = "//   * Модели         - ТаблицаЗначений - карта доступности T8;"

OLD_4 = """			Для Каждого СтрДок Из ДокументОбъект.ОсновнаяТехника Цикл
				Если СтрДок.МодельТехники = Замена Тогда
					СтрокаЗамены = СтрДок;
				ИначеЕсли СтрДок.МодельТехники = БезКандидата Тогда
					СтрокаДефицита = СтрДок;
				Иначе
					// Прочие модели в тесте не создаются.
				КонецЕсли;
			КонецЦикла;"""

NEW_4 = """			Для Каждого СтрДок Из ДокументОбъект.ОсновнаяТехника Цикл
				Если СтрДок.МодельТехники = Замена Тогда
					СтрокаЗамены = СтрДок;
				КонецЕсли;
				Если СтрДок.МодельТехники = БезКандидата Тогда
					СтрокаДефицита = СтрДок;
				КонецЕсли;
			КонецЦикла;"""


def main():
    srv = SRV.read_bytes()[3:].decode("utf-8")
    for old, new, tag in ((OLD_1, NEW_1, "1"), (OLD_2, NEW_2, "2"),
                          (OLD_3, NEW_3, "3")):
        assert srv.count(old) == 1, f"srv якорь {tag} не найден"
        srv = srv.replace(old, new)
    SRV.write_bytes(BOM + srv.encode("utf-8"))

    tst = TST.read_bytes()[3:].decode("utf-8")
    assert tst.count(OLD_4) == 1, "tst якорь 4 не найден"
    tst = tst.replace(OLD_4, NEW_4)
    TST.write_bytes(BOM + tst.encode("utf-8"))
    print("t9_fix2: inline comment, docstrings, test ifs")


if __name__ == "__main__":
    main()
