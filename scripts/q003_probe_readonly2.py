import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import datetime
import win32com.client

CONN = "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';"
CUT_DATE = datetime.datetime(2026, 11, 9, 23, 59, 59)


def q(agent, text, params=None):
    r = agent.NewObject("Запрос")
    r.Текст = text
    if params:
        for k, v in params.items():
            r.УстановитьПараметр(k, v)
    return r.Выполнить().Выгрузить()


def main():
    agent = win32com.client.Dispatch("V85.COMConnector").Connect(CONN)
    print("connected")

    print("\n== A. Распределение периодов в истории ТС")
    for r in q(agent, """ВЫБРАТЬ Ист.Период КАК Период, КОЛИЧЕСТВО(*) КАК К
            ИЗ РегистрСведений.АпкИсторияТранспортныхСредств КАК Ист
            СГРУППИРОВАТЬ ПО Ист.Период УПОРЯДОЧИТЬ ПО Период"""):
        print("   %s -> %s записей" % (str(r.Период)[:10], r.К))

    print("\n== B. История по машинам, которые есть в документе плана")
    rows = q(agent, """ВЫБРАТЬ
        ТЧ.ТранспортноеСредство.Наименование КАК ТС,
        КОЛИЧЕСТВО(Ист.ТранспортноеСредство) КАК Записей,
        КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Ист.ЭксплуатирующееПодразделение) КАК Подразделений,
        КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Ист.Организация) КАК Организаций
        ИЗ Документ.АпкПланТехническихРесурсов.Техника КАК ТЧ
            ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АпкИсторияТранспортныхСредств КАК Ист
            ПО Ист.ТранспортноеСредство = ТЧ.ТранспортноеСредство
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
            ПО Д.Ссылка = ТЧ.Ссылка
        ГДЕ Д.Проведен
        СГРУППИРОВАТЬ ПО ТЧ.ТранспортноеСредство
        УПОРЯДОЧИТЬ ПО Записей УБЫВ""")
    for r in rows:
        print("   %-38s записей=%s подразделений=%s организаций=%s" % (
            r.ТС[:38], r.Записей, r.Подразделений, r.Организаций))

    print("\n== C. Срез последних на дату документа: приписка машин плана")
    for r in q(agent, """ВЫБРАТЬ
        ТЧ.ТранспортноеСредство.Наименование КАК ТС,
        Срез.ЭксплуатирующееПодразделение.Наименование КАК Подразделение,
        Срез.Организация.Наименование КАК Организация,
        Срез.Период КАК Период
        ИЗ Документ.АпкПланТехническихРесурсов.Техника КАК ТЧ
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
            ПО Д.Ссылка = ТЧ.Ссылка
            ЛЕВОЕ СОЕДИНЕНИЕ РегистрСведений.АпкИсторияТранспортныхСредств.СрезПоследних(
                &ДатаСреза, ) КАК Срез
            ПО Срез.ТранспортноеСредство = ТЧ.ТранспортноеСредство
        ГДЕ Д.Проведен""", {"ДатаСреза": CUT_DATE}):
        print("   %-38s подр=%-18s орг=%-10s период=%s" % (
            r.ТС[:38], (r.Подразделение or "-")[:18], (r.Организация or "-")[:10], str(r.Период)[:10]))

    print("\n== D. Значения перечисления принадлежности ТС")
    try:
        for r in q(agent, """ВЫБРАТЬ П.Ссылка КАК С, П.Наименование КАК Н
                ИЗ Перечисление.АпкПринадлежностьТС КАК П"""):
            print("   ", r.Н)
    except Exception as e:
        print("   ошибка:", e)

    print("\n== E. Помеченные на удаление / без модели среди машин плана")
    for r in q(agent, """ВЫБРАТЬ
        ТЧ.ТранспортноеСредство.Наименование КАК ТС,
        ТЧ.ТранспортноеСредство.ПометкаУдаления КАК Пометка,
        ТЧ.ТранспортноеСредство.АпкМодель КАК Модель
        ИЗ Документ.АпкПланТехническихРесурсов.Техника КАК ТЧ
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
            ПО Д.Ссылка = ТЧ.Ссылка
        ГДЕ Д.Проведен"""):
        print("   %-38s пометка=%s модель_заполнена=%s" % (
            r.ТС[:38], r.Пометка, r.Модель is not None))


if __name__ == "__main__":
    main()
