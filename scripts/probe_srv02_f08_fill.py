#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Probe: in-memory ЗаполнитьПланРабот (params as VA feature 08) - dump demand/замещение detail."""
import sys
import win32com.client

conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';")

def out(s):
    sys.stdout.buffer.write((s + "\n").encode("utf-8"))

S = conn.NewObject("Структура")
S.Вставить("СценарийПланирования", conn.Справочники.АпкСценарииПланирования.НайтиПоНаименованию("Основной"))
S.Вставить("Организация", conn.Справочники.Организации.НайтиПоНаименованию("НИВА"))
S.Вставить("Подразделение", conn.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Отделение №2"))
q = conn.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2014, 1, 1) КАК Д"
v = q.Выполнить().Выбрать(); v.Следующий(); S.Вставить("ДатаНачала", v.Д)
q = conn.NewObject("Запрос")
q.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2015, 12, 31) КАК Д"
v = q.Выполнить().Выбрать(); v.Следующий(); S.Вставить("ДатаОкончания", v.Д)
S.Вставить("ДнейПериода", 10)
S.Вставить("СменВдень", 1)

# demand
P = conn.Тх_ТехникаСервер.ПотребностьПоТехкартам(S).Выгрузить()
out("=== ПотребностьПоТехкартам: %d строк" % P.Количество())
for i in range(P.Количество()):
    r = P.Получить(i)
    m = r.МодельТехники
    out("  demand[%d]: model=%r (%s) вид=%s смен=%s часов=%s"
        % (i, m.Наименование if m.Код or m.Наименование else "", m.Код,
           r.ВидТехники, r.ПотребностьСмен, r.ПотребностьЧасов))

# availability
D = conn.Тх_ТехникаСервер.ДоступныеМоделиПодразделения(S)
out("=== Доступность: ПланОтсутствует=%s, моделей=%d" % (D.ПланОтсутствует, D.Модели.Количество()))
for i in range(D.Модели.Количество()):
    r = D.Модели.Получить(i)
    m = r.МодельТехники
    out("  avail[%d]: model=%r код=%s тип=%s единиц=%s"
        % (i, m.Наименование, m.Код, r.ТипТС, r.ЕдиницДоступно))

# full formation in-memory
Doc = conn.Документы.АпкПланТехническихРесурсов.СоздатьДокумент()
Sv = conn.Тх_ТехникаСервер.ЗаполнитьПланРабот(Doc, S)
out("=== Сводка: строк=%s смен=%s часов=%s замещ=%s дефицит=%s планОтсут=%s"
    % (Sv.КоличествоСтрок, Sv.ВсегоСмен, Sv.ВсегоЧасов, Sv.ЗамещенныхСтрок,
       Sv.ДефицитныхСтрок, Sv.ПланОтсутствует))
SP = Sv.СтрокиПлана
out("=== СтрокиПлана: %d" % SP.Количество())
for i in range(SP.Количество()):
    r = SP.Получить(i)
    m = r.МодельТехники
    z = r.Замещение
    out("  plan[%d]: model=%r(%s) смен=%s часов=%s единиц=%s замена=%r коммент=%r"
        % (i, m.Наименование if m else "", m.Код if m else "",
           r.ПотребностьСмен, r.ПотребностьЧасов, r.Единиц,
           z.Наименование if z else None, r.Комментарий))
out("=== Doc ТЧ: Тех=%d Обор=%d Авто=%d Приц=%d Подр=%d"
    % (Doc.Техника.Количество(), Doc.Оборудование.Количество(),
       Doc.Автотранспорт.Количество(), Doc.Прицепы.Количество(),
       Doc.Подразделения.Количество()))
