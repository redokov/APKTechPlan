def delete_proc(text, name):
    """Удаляет процедуру/функцию с блоком комментария над ней."""
    m = re.search(r"^(Процедура|Функция)\s+" + name + r"\b", text, re.M)
    if not m:
        return text, 0
    start = m.start()
    # контекстный комментарий: непрерывные // строки выше
    lines_before = text[:start].split("\r\n")
    k = len(lines_before) - 1
    while k > 0 and lines_before[k - 1].lstrip().startswith("//"):
        k -= 1
    # k указывает первую строку комментария; пересчёт offset
    comment_start = start - sum(len(l) + 2 for l in lines_before[k:len(lines_before) - 1])
    kind = m.group(1)
    endmark = {"Функция": "КонецФункции", "Процедура": "КонецПроцедуры"}[kind]
    e = text.find(endmark, m.end())
    assert e > 0
    e = text.find("\r\n", e) + 2
    return text[:comment_start] + text[e:], 1


def delete_region(text, region):
    m = re.search(r"#Область\s+" + region + r"\r\n", text)
    if not m:
        return text, 0
    start = m.start()
    # начало региона вместе с комментарием над ним
    lines_before = text[:start].split("\r\n")
    k = len(lines_before) - 1
    while k > 0 and lines_before[k - 1].lstrip().startswith("//"):
        k -= 1
    cstart = start - sum(len(l) + 2 for l in lines_before[k:len(lines_before) - 1])
    e = text.find("#КонецОбласти\r\n", m.end())
    assert e > 0
    e += len("#КонецОбласти\r\n")
    return text[:cstart] + text[e:], 1


