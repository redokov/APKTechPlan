def main():
    # 1. файлы
    for rel in ["InformationRegisters/Тх_КоэффициентыПересчетаРабот.xml",
                "DataProcessors/Тх_ЗаполнениеКоэффициентов.xml"]:
        p = SRC / rel
        if p.exists():
            p.unlink()
            check(True, f"1: удалён {rel.split('/')[-1]}")
    for rel in ["InformationRegisters/Тх_КоэффициентыПересчетаРабот",
                "DataProcessors/Тх_ЗаполнениеКоэффициентов"]:
        p = SRC / rel
        if p.is_dir():
            shutil.rmtree(p)
            check(True, f"1: удалён каталог {rel.split('/')[-1]}")

    # 2. Configuration.xml
    p = SRC / "Configuration.xml"
    t = load_xml(p)
    for line in ["\t\t\t<DataProcessor>Тх_ЗаполнениеКоэффициентов</DataProcessor>\r\n",
                 "\t\t\t<InformationRegister>Тх_КоэффициентыПересчетаРабот</InformationRegister>\r\n"]:
        c = t.count(line)
        check(c == 1, f"2: ChildObjects строка ({c})")
        t = t.replace(line, "", 1)
    save_xml(p, t)

    # 3. Subsystem.xml
    p = SRC / "Subsystems/Тх_ПланированиеТехники.xml"
    t = load_xml(p)
    for line in ['\t\t\t\t<xr:Item xsi:type="xr:MDObjectRef">InformationRegister.Тх_КоэффициентыПересчетаРабот</xr:Item>\r\n',
                 '\t\t\t\t<xr:Item xsi:type="xr:MDObjectRef">DataProcessor.Тх_ЗаполнениеКоэффициентов</xr:Item>\r\n']:
        c = t.count(line)
        check(c == 1, f"3: Content строка ({c})")
        t = t.replace(line, "", 1)
    save_xml(p, t)

    # 4. CommandInterface.xml (блоки в CommandsVisibility и CommandsOrder)
    p = SRC / "Subsystems/Тх_ПланированиеТехники/Ext/CommandInterface.xml"
    t = load_xml(p)
    for cmd in ["InformationRegister.Тх_КоэффициентыПересчетаРабот.StandardCommand.OpenList",
                "DataProcessor.Тх_ЗаполнениеКоэффициентов.StandardCommand.Open"]:
        pat = re.compile(r"\t*<Command name=\"" + re.escape(cmd) + r"\">.*?</Command>\r\n", re.S)
        t2, n = pat.subn("", t)
        check(n == 2, f"4: блоки Command {cmd.split('.')[0]} ({n}/2)")
        t = t2
    save_xml(p, t)

    # 5. Roles
    for role in ["Тх_Чтение", "Тх_Редактирование"]:
        p = SRC / f"Roles/{role}/Ext/Rights.xml"
        t = load_xml(p)
        for obj in ["InformationRegister.Тх_КоэффициентыПересчетаРабот",
                    "DataProcessor.Тх_ЗаполнениеКоэффициентов"]:
            pat = re.compile(r"\t*<object>\s*<name>" + re.escape(obj) + r"</name>.*?</object>\r\n", re.S)
            t2, n = pat.subn("", t, count=1)
            check(n == 1, f"5: {role} / {obj.split('.')[-1]}")
            t = t2
        save_xml(p, t)

    # 6. серверный модуль
    t = load(P_SRV)
    t = part6(t)
    assert "Тх_КоэффициентыПересчетаРабот" not in t, "6: остаточные ссылки в сервере"
    save(P_SRV, t)

    # 7. тесты
    t = load(P_TST)
    t = part7(t)
    assert "Тх_КоэффициентыПересчетаРабот" not in t.replace("Тх_ДефицитТехники", ""), "7: остаточные ссылки в тестах"
    save(P_TST, t)

    # 8. раннер
    t = load(P_RUN)
    t = t.replace("все 20 тестов", "все 13 тестов")
    kill = ["ЗапуститьТестКоэффициентБазовойМоделиЕдиница", "ЗапуститьТестОтказДвеБазовыеМодели",
            "ЗапуститьТестДубльКоэффициентовНевозможен", "ЗапуститьТестАвтозаполнениеПоМощности",
            "ЗапуститьТестАвтозаполнениеМодельБезМощности", "ЗапуститьТестКоэффициентНаДатуСрезПоследних",
            "ЗапуститьТестПересчетДоступностиЧерезКоэффициент",
            "ЗапуститьТестКоэффициентНеЗаданМодельИсключенаИСтрокаПомечена",
            "ЗапуститьТестТранспортныеРаботыМодельВМодельБезКоэффициентов"]
    for k in kill:
        t, d = delete_proc(t, k)
        assert d == 1, f"8: обёртка {k}"
        t = t.replace("\t%s(Результаты);\r\n" % k, "", 1)
    t = t.replace("\tЗапуститьТестВалидацииGenericТипов(Результаты);\r\n",
                  "\tЗапуститьТестВалидацииGenericТипов(Результаты);\r\n"
                  "\tЗапуститьТестДоступноСменЧерезЗамещение(Результаты);\r\n"
                  "\tЗапуститьТестДоступноСменЗамещениеНеЗадан(Результаты);\r\n", 1)
    wraps = ""
    for test in ["ТестДоступноСменЧерезЗамещение", "ТестДоступноСменЗамещениеНеЗадан"]:
        wraps += '''// Обёртка вызова теста %s.
//
Процедура Запустить%s(Результаты)

\tИмяТеста = "%s";
\tНачалоТеста = ТекущаяУниверсальнаяДатаВМиллисекундах();
\tПрошёл = Ложь;
\tПопытка
\t\tПрошёл = Тх_Тесты.%s();
\tИсключение
\t\tПрошёл = Ложь;
\t\tСообщитьОбИсключенииТеста(ИмяТеста, ОписаниеОшибки());
\tКонецПопытки;
\tЗафиксироватьРезультат(Результаты, ИмяТеста, Прошёл, НачалоТеста);

КонецПроцедуры

''' % (test, test, test, test)
    tail = "#КонецОбласти\r\n"
    i = t.rfind(tail)
    t = t[:i] + wraps.replace("\n", "\r\n") + t[i:]
    n_calls = len(re.findall(r"^\tЗапуститьТест\w+\(Результаты\);", t, re.M))
    check(n_calls == 13, f"8: раннер вызывает {n_calls} тестов (ожидалось 13)")
    save(P_RUN, t)

    # 9. run_unit_tests.py
    t = P_UT.read_text(encoding="utf-8")
    t = t.replace("all 20 tests", "all 13 tests").replace("total != 20", "total != 13").replace("expected 20 tests", "expected 13 tests")
    P_UT.write_text(t, encoding="utf-8", newline="")
    check("total != 13" in t, "9: run_unit_tests.py ожидает 13")

    # 10. РасчетДефицита комментарий (упоминание удалённой обработки)
    t = load(P_RAS)
    t = t.replace(
        "// клиента недоступен (FAQ Q8), значение продублировано в клиентском модуле\r\n"
        "// (как в Тх_ЗаполнениеКоэффициентов).\r\n",
        "// клиента недоступен (FAQ Q8), значение продублировано в клиентском модуле.\r\n")
    save(P_RAS, t)
    check("Тх_ЗаполнениеКоэффициентов" not in t, "10: комментарий РасчетДефицита чист")
    # 10b: T6-фикс - СуффиксОбъема вызывается из &НаСервере (дефект с базовой
    # линии A8+A9: клиентская директива не компилируется в серверном контексте).
    old10 = "&НаКлиенте\r\nФункция СуффиксОбъема()"
    new10 = ("&НаСервере\r\nФункция СуффиксОбъема()\r\n\r\n\t"
             "// Контекст сервера: вызывается из РассчитатьДефицитНаСервере (T6-фикс:\r\n\t"
             "// вызов клиентской функции из серверного контекста не компилируется).")
    assert t.count(old10) == 1
    t = t.replace(old10, new10)
    save(P_RAS, t)

    print("RESULT:", "PASS" if ok_all else "FAIL")
    sys.exit(0 if ok_all else 1)


if __name__ == "__main__":
    main()
