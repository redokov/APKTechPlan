#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T8 fix3: оператор В ИЕРАРХИИ принимает только ПАРАМЕТР справа
(поле таблицы -> runtime "Неверные параметры В ИЕРАРХИИ").

Проверка «заданное подразделение входит в иерархию строк ТЧ Подразделения»
развёрнута в обратную сторону: в коде собирается цепочка ancestors
(сам подразделение + Родитель + ...), и строки ТЧ проверяются
В (&ИерархияПодразделений). Эквивалентно для иерархии элементов
СтруктураПредприятия (HierarchyOfItems, стандартный реквизит Parent).
"""
import pathlib

SRV = pathlib.Path(
    "src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_ТехникаСервер/Ext/Module.bsl")

BOM = bytes([0xEF, 0xBB, 0xBF])

OLD_A = """	// Шаг 1 - проведённые документы плана по отборам. Подразделение
	// проверяется В ИЕРАРХИИ строк ТЧ Подразделения; РАЗЛИЧНЫЕ защищает
	// от раздувания счётчика при нескольких строках подразделений.
	УсловияОтбора = "Д.Проведен"""

NEW_A = """	// Шаг 1 - проведённые документы плана по отборам. В ИЕРАРХИИ
	// принимает только параметр, поэтому проверка «подразделение входит
	// в иерархию строк ТЧ» развёрнута в обратную: собираются сам
	// подразделение и все его родители (цепочка Родитель), и строки ТЧ
	// Подразделения проверяются В (&ИерархияПодразделений); РАЗЛИЧНЫЕ
	// защищает от раздувания счётчика при нескольких строках.
	ИерархияПодразделений = Неопределено;
	Если ЗначениеЗаполнено(Подразделение) Тогда
		ИерархияПодразделений = Новый Массив;
		Текущий = Подразделение;
		Пока ЗначениеЗаполнено(Текущий) Цикл
			ИерархияПодразделений.Добавить(Текущий);
			Текущий = Текущий.Родитель;
		КонецЦикла;
	КонецЕсли;

	УсловияОтбора = "Д.Проведен"""

OLD_B = """	УсловиеПодразделения = "";
	Если ЗначениеЗаполнено(Подразделение) Тогда
		УсловиеПодразделения = "
	|	И &Подразделение В ИЕРАРХИИ (Подр.Подразделение)";
	КонецЕсли;"""

NEW_B = """	УсловиеПодразделения = "";
	Если ЗначениеЗаполнено(Подразделение) Тогда
		УсловиеПодразделения = "
	|	И Подр.Подразделение В (&ИерархияПодразделений)";
	КонецЕсли;"""

OLD_C = """	ПараметрыЗапроса = Новый Структура(
		"СценарийПланирования", Параметры.СценарийПланирования);
	Если ЗначениеЗаполнено(Организация) Тогда
		ПараметрыЗапроса.Вставить("Организация", Организация);
	КонецЕсли;
	Если ЗначениеЗаполнено(Подразделение) Тогда
		ПараметрыЗапроса.Вставить("Подразделение", Подразделение);
	КонецЕсли;

	ДокументыПлана"""

NEW_C = """	ПараметрыЗапроса = Новый Структура(
		"СценарийПланирования", Параметры.СценарийПланирования);
	Если ЗначениеЗаполнено(Организация) Тогда
		ПараметрыЗапроса.Вставить("Организация", Организация);
	КонецЕсли;
	Если ЗначениеЗаполнено(Подразделение) Тогда
		ПараметрыЗапроса.Вставить("ИерархияПодразделений",
			ИерархияПодразделений);
	КонецЕсли;

	ДокументыПлана"""


def main():
    t = SRV.read_bytes()[3:].decode("utf-8")
    for old, new, tag in ((OLD_A, NEW_A, "A"),
                          (OLD_B, NEW_B, "B"),
                          (OLD_C, NEW_C, "C")):
        assert t.count(old) == 1, f"якорь {tag} не найден или неоднозначен"
        t = t.replace(old, new)
    SRV.write_bytes(BOM + t.encode("utf-8"))
    print("t8_fix3: ancestors-walk + V(&IerarhijaPodrazdelenij)")


if __name__ == "__main__":
    main()
