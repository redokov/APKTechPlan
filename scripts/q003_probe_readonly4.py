import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client

CONN = "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';"
PARTS = ["Техника", "Оборудование", "Автотранспорт", "Прицепы"]
MDL = {
    "Техника": "АпкМоделиСХТехники",
    "Оборудование": "АпкМоделиСХОборудования",
    "Автотранспорт": "АпкМоделиАвтотранспорта",
    "Прицепы": "АпкМоделиПрицепов",
}


def q(agent, text):
    r = agent.NewObject("Запрос")
    r.Текст = text
    return r.Выполнить().Выгрузить()


def main():
    agent = win32com.client.Dispatch("V85.COMConnector").Connect(CONN)
    print("connected")

    print("\n== A. Одна машина в двух разных табличных частях одного документа")
    union = "\nОБЪЕДИНИТЬ ВСЕ\n".join([
        """ВЫБРАТЬ Д.Номер КАК Номер, ТЧ.ТранспортноеСредство КАК ТС, "%s" КАК Часть
        ИЗ Документ.АпкПланТехническихРесурсов.%s КАК ТЧ
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
            ПО Д.Ссылка = ТЧ.Ссылка""" % (p, p) for p in PARTS])
    rows = q(agent, """ВЫБРАТЬ Номер, ТС, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Часть) КАК Частей,
            КОЛИЧЕСТВО(*) КАК Строк
        ИЗ (""" + union + """) КАК Все
        СГРУППИРОВАТЬ ПО Номер, ТС
        ИМЕЮЩИЕ КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Часть) > 1""")
    n = list(rows)
    print("   машин в нескольких частях:", len(n))
    for r in n[:10]:
        print("     документ %s строк=%s частей=%s" % (r.Номер, r.Строк, r.Частей))

    print("\n== B. Соответствие части и типа модели машины")
    for part in PARTS:
        expect = MDL[part]
        bad = q(agent, """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К
            ИЗ Документ.АпкПланТехническихРесурсов.%s КАК ТЧ
                ВНУТРЕННЕЕ СОЕДИНЕНИЕ Справочник.ТранспортныеСредства КАК ТС
                ПО ТС.Ссылка = ТЧ.ТранспортноеСредство
            ГДЕ НЕ ТС.АпкМодель ССЫЛКА Справочник.%s""" % (part, expect))
        ok = q(agent, """ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К
            ИЗ Документ.АпкПланТехническихРесурсов.%s КАК ТЧ
                ВНУТРЕННЕЕ СОЕДИНЕНИЕ Справочник.ТранспортныеСредства КАК ТС
                ПО ТС.Ссылка = ТЧ.ТранспортноеСредство
            ГДЕ ТС.АпкМодель ССЫЛКА Справочник.%s""" % (part, expect))
        print("   ТЧ %-14s ожидается модель %-24s соответствуют=%-3s прочие=%s" % (
            part, expect, ok[0].К, bad[0].К))

    print("\n== C. Все документы всех сценариев (включая непроведённые)")
    for r in q(agent, """ВЫБРАТЬ Д.Номер КАК Номер, Д.Проведен КАК Проведен,
            Д.СценарийПланирования.Наименование КАК Сценарий
            ИЗ Документ.АпкПланТехническихРесурсов КАК Д
            УПОРЯДОЧИТЬ ПО Д.Дата"""):
        print("   %s | проведен=%s | сценарий=%s" % (r.Номер, r.Проведен, r.Сценарий))


if __name__ == "__main__":
    main()
