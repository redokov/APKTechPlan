# -*- coding: utf-8 -*-
"""Probe: rekвизиты замещения моделей (demo vs Тх_Тест Базовая) + КоэффициентЗамещения."""
import sys
import win32com.client

conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';")

def out(s):
    sys.stdout.buffer.write((s + "\n").encode("utf-8"))

attrs = ["КоэффициентПереводаВУЭГА", "ШиринаОбработки", "ОбъемБункера", "МощностьДвигателя"]

models = ["МТЗ-82", "John Deer", "Тх_Тест Базовая"]
for name in models:
    ref = conn.Справочники.АпкМоделиСХТехники.НайтиПоНаименованию(name)
    if not ref.Ссылка if hasattr(ref, "Ссылка") else False:
        pass
    out("== %s (пустая=%s)" % (name, ref.Пустая()))
    for a in attrs:
        q = conn.NewObject("Запрос")
        q.Текст = "ВЫБРАТЬ Спр." + a + " КАК З ИЗ Справочник.АпкМоделиСХТехники КАК Спр ГДЕ Спр.Ссылка = &Р"
        q.УстановитьПараметр("Р", ref)
        try:
            v = q.Выполнить().Выбрать()
            v.Следующий()
            out("   %s = %s" % (a, v.З))
        except Exception as e:
            out("   %s = ERR %s" % (a, str(e)[:80]))

m1 = conn.Справочники.АпкМоделиСХТехники.НайтиПоНаименованию("МТЗ-82")
m2 = conn.Справочники.АпкМоделиСХТехники.НайтиПоНаименованию("Тх_Тест Базовая")
k = conn.Тх_ТехникаСервер.КоэффициентЗамещения(m1, m2)
out("К(МТЗ-82 -> Тх_Тест Базовая) = %r" % k)
r1 = conn.Тх_ТехникаСервер.РеквизитЗамещения(m1)
out("РеквизитЗамещения(МТЗ-82) = %r" % (r1.Реквизит + " = " + str(r1.Значение) if r1 else None))
r2 = conn.Тх_ТехникаСервер.РеквизитЗамещения(m2)
out("РеквизитЗамещения(Тх_Тест Базовая) = %r" % (r2.Реквизит + " = " + str(r2.Значение) if r2 else None))
