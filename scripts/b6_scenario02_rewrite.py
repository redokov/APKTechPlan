#!/usr/bin/env python3
"""B6: rewrite scenario 02 for the НТТ-compatible fill pattern."""
import io

p = 'tests/vanessa/02-avtozapolnenie-po-moshchnosti.feature'
s = io.open(p, encoding='utf-8', newline='').read()

# 1. Context: cleanup test data of the register (idempotent runs)
old_ctx = "Контекст:\r\n\tДано Я запускаю сценарий открытия TestClient или подключаю уже существующий\r\n"
new_ctx = (old_ctx +
           "\t# Очистка тест-данных сценария (идемпотентность повторных прогонов)\r\n"
           "\tДано я выполняю код встроенного языка на сервере\r\n"
           "\t|Набор = РегистрыСведений.Тх_КоэффициентыПересчетаРабот.СоздатьНаборЗаписей();|\r\n"
           "\t|Набор.Отбор.Работа.Установить(Справочники.ВидыРаботСотрудников.НайтиПоНаименованию(\"Тх_Тест Работа\"));|\r\n"
           "\t|Набор.Записать();|\r\n")
assert old_ctx in s
s = s.replace(old_ctx, new_ctx)

# 2. Fill pattern for Работа (twice) and БазоваяМодель -> БазоваяМодельСХТехники
old_fill_work = ("\tИ я нажимаю кнопку выбора у поля с именем 'Работа'\r\n"
                 "\tИ В открытой форме в поле с именем 'СписокСтрокаПоиска' я ввожу текст 'Тх_Тест'\r\n"
                 "\tИ в таблице 'Список' я перехожу к строке:\r\n"
                 "\t\t| 'Наименование' |\r\n"
                 "\t\t| 'Тх_Тест Работа' |\r\n"
                 "\tИ в таблице 'Список' я выбираю текущую строку\r\n")
new_fill_work = ("\tИ в поле с именем 'Работа' я ввожу текст 'Тх_Тест Работа'\r\n"
                 "\tИ из выпадающего списка с именем 'Работа' я выбираю точное значение 'Тх_Тест Работа'\r\n")
count = s.count(old_fill_work)
assert count >= 1, "work fill not found"
s = s.replace(old_fill_work, new_fill_work)

old_fill_base = ("\tИ я нажимаю кнопку выбора у поля с именем 'БазоваяМодель'\r\n"
                 "\tИ В открытой форме в поле с именем 'СписокСтрокаПоиска' я ввожу текст 'Тх_Тест'\r\n"
                 "\tИ в таблице 'Список' я перехожу к строке:\r\n"
                 "\t\t| 'Наименование' |\r\n"
                 "\t\t| 'Тх_Тест Базовая' |\r\n"
                 "\tИ в таблице 'Список' я выбираю текущую строку\r\n")
new_fill_base = ("\tИ в поле с именем 'БазоваяМодельСХТехники' я ввожу текст 'Тх_Тест Базовая'\r\n"
                 "\tИ из выпадающего списка с именем 'БазоваяМодельСХТехники' я выбираю точное значение 'Тх_Тест Базовая'\r\n")
count = s.count(old_fill_base)
assert count >= 1, "base fill not found"
s = s.replace(old_fill_base, new_fill_base)

# 3. Remove «пауза» steps (no such VA step in 1.2.043)
s = s.replace("\tИ пауза 2\r\n", "")

# 4. Register list checks: drop search-string lines (element absent in НТТ)
s = s.replace("\tИ В открытой форме в поле с именем 'СписокСтрокаПоиска' я ввожу текст 'Тх_Тест'\r\n", "")

# 5. Message-log check -> server state check (models without power get no row)
old_msg = ("\t# 2. Модели без мощности: строка не создаётся, имя модели — в сообщении\r\n"
           "\t# (фактическое сообщение: «Модели без мощности двигателя (строки не созданы): ...»)\r\n"
           "\tИ в логе сообщений TestClient есть строки:\r\n"
           "\t\t| 'Текст' |\r\n"
           "\t\t| 'мощности' |\r\n")
new_msg = ("\t# 2. Модели без мощности: строка не создаётся (проверка состояния\r\n"
           "\t# вместо лога сообщений - шаг лога сообщений несовместим с 8.5)\r\n"
           "\tКогда я выполняю код встроенного языка на сервере\r\n"
           "\t|Запрос = Новый Запрос(\"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК N ИЗ РегистрСведений.Тх_КоэффициентыПересчетаРабот КАК К ГДЕ К.МодельТехники = &М\");|\r\n"
           "\t|Запрос.УстановитьПараметр(\"М\", Справочники.АпкМоделиСХТехники.НайтиПоНаименованию(\"Тх_Тест БезМощности\"));|\r\n"
           "\t|Если Запрос.Выполнить().Выгрузить()[0].N <> 0 Тогда ВызватьИсключение \"строка без мощности не должна была создаться\"; КонецЕсли;|\r\n")
assert old_msg in s, "message block not found"
s = s.replace(old_msg, new_msg)

io.open(p, 'w', encoding='utf-8', newline='').write(s)
print('scenario 02 rewritten')
