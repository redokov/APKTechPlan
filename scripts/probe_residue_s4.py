import sys
import win32com.client

conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';")

def out(s):
    sys.stdout.buffer.write((s + "\n").encode("utf-8"))

def scalar(txt):
    q = conn.NewObject("Запрос")
    q.Текст = txt
    v = q.Выполнить().Выбрать()
    v.Следующий()
    return v.Н

n = scalar('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ Документ.АпкПланТехническихРесурсов КАК С '
           'ГДЕ С.Организация.Наименование = "НИВА" И С.СценарийПланирования.Наименование = "Основной"')
out("планы НИВА/Основной (все): %s" % n)
n = scalar('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ Документ.АпкПланТехническихРесурсов КАК С '
           'ГДЕ С.Проведен И С.Организация.Наименование = "НИВА" И С.СценарийПланирования.Наименование = "Основной"')
out("планы НИВА/Основной (проведённые): %s" % n)
n = scalar('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрСведений.АпкИсторияТранспортныхСредств КАК Р '
           'ГДЕ Р.ТранспортноеСредство.Код ПОДОБНО "ТХТС%"')
out("приписки ТХТС* в регистре: %s" % n)
n = scalar('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрСведений.АпкИсторияТранспортныхСредств КАК Р '
           'ГДЕ Р.ТранспортноеСредство.Наименование ПОДОБНО "Тх_VA% ТС%"')
out("приписки Тх_VA%% ТС в регистре: {}".format(n))
n = scalar('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ Справочник.ТранспортныеСредства КАК Спр '
           'ГДЕ Спр.Наименование ПОДОБНО "Тх_VA% ТС%" И НЕ Спр.ПометкаУдаления')
out("элементы ТС Тх_VA%% ТС (живые): {}".format(n))
n = scalar('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ Справочник.ТранспортныеСредства КАК Спр '
           'ГДЕ Спр.Код ПОДОБНО "ТХТС%" И НЕ Спр.ПометкаУдаления')
out("элементы ТС ТХТС* (va_prep_data): {}".format(n))
n = scalar('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ Справочник.ТранспортныеСредства КАК Спр '
           'ГДЕ (Спр.Наименование ПОДОБНО "Тх_VA%" ИЛИ Спр.Наименование ПОДОБНО "Тх_Тест%") И Спр.ПометкаУдаления')
out("элементы ТС с маркерами в корзине (помечены на удаление): %s" % n)
n = scalar('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрСведений.Тх_ДефицитТехники КАК Р '
           'ГДЕ Р.Организация.Наименование = "НИВА"')
out("строки дефицита НИВА (справочно, демо-спрос): %s" % n)
# SRV-01 (2026-11-13): фикстуры периодных тестов - клоны строк с периодами
# 2098-2099 (январь/февраль/граница). Тесты восстанавливают снимок, но
# при сбое посередине синтетика может остаться - ловим по диапазону.
n = scalar('ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрСведений.Тх_ДефицитТехники КАК Р '
           'ГДЕ Р.ПериодНачала >= ДАТАВРЕМЯ(2098, 1, 1)')
out("строки дефицита 2098+ (остатки синтетики SRV-01): %s" % n)
