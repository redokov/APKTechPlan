#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Probe: residue docs АпкПланТехническихРесурсов from VA 08 runs - what formation produced."""
import sys
import win32com.client

conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';")

def out(s):
    sys.stdout.buffer.write((s + "\n").encode("utf-8"))

q = conn.NewObject("Запрос")
q.Текст = ("ВЫБРАТЬ С.Ссылка, С.Номер, С.Дата, С.Проведен, С.Комментарий, С.ПредставлениеПодразделений ИЗ "
           "Документ.АпкПланТехническихРесурсов КАК С "
           "ГДЕ С.Организация = &Орг И С.СценарийПланирования = &Сцен "
           "УПОРЯДОЧИТЬ ПО С.Дата УБЫВ")
q.УстановитьПараметр("Орг", conn.Справочники.Организации.НайтиПоНаименованию("НИВА"))
q.УстановитьПараметр("Сцен", conn.Справочники.АпкСценарииПланирования.НайтиПоНаименованию("Основной"))
sel = q.Выполнить().Выбрать()
n = 0
while sel.Следующий():
    n += 1
    d = sel.Ссылка
    tcnt = d.Техника.Количество()
    ocnt = d.Оборудование.Количество()
    acnt = d.Автотранспорт.Количество()
    pcnt = d.Прицепы.Количество()
    prcnt = d.Подразделения.Количество()
    out("doc %s | posted=%s | date=%s | kom=%r | predpr=%r | Подр=%d Тех=%d Обор=%d Авто=%d Приц=%d"
        % (sel.Номер, sel.Проведен, sel.Дата, sel.Комментарий, sel.ПредставлениеПодразделений,
           prcnt, tcnt, ocnt, acnt, pcnt))
    # sample Техника rows: ТС код/наименование
    for i in range(min(tcnt, 5)):
        row = d.Техника.Получить(i)
        tc = row.ТранспортноеСредство
        out("   Техника[%d]: код=%r наим=%r" % (i, tc.Код, tc.Наименование))
    for i in range(min(ocnt, 3)):
        row = d.Оборудование.Получить(i)
        tc = row.ТранспортноеСредство
        out("   Оборудование[%d]: код=%r наим=%r" % (i, tc.Код, tc.Наименование))
    for i in range(min(acnt, 3)):
        row = d.Автотранспорт.Получить(i)
        tc = row.ТранспортноеСредство
        out("   Автотранспорт[%d]: код=%r наим=%r" % (i, tc.Код, tc.Наименование))
    for i in range(min(pcnt, 3)):
        row = d.Прицепы.Получить(i)
        tc = row.ТранспортноеСредство
        out("   Прицепы[%d]: код=%r наим=%r" % (i, tc.Код, tc.Наименование))
out("total docs (НИВА/Основной): %d" % n)
