#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T9 fix4 (runtime: ОКРВВЕРХ не существует в языке платформы).

Unit-прогон упал на инициализации Тх_Тесты(1457): «Процедура или функция
с указанным именем не определена (ОКРВВЕРХ)». Подтверждено
bsl-platform-context: в глобальном контексте 8.5 есть только Окр и Цел.
Дизайн-нотация «Количество = ОКРВВЕРХ(...)» (design 6.3) реализуется
хелпером ОкруглитьВверх (потолок положительного числа).

 1. Тх_ТехникаСервер: + Функция ОкруглитьВверх(Значение) Экспорт
    (region ФормированиеПланаРабот, перед докстрингом ЗаполнитьПланРабот).
 2. Движок (1311): ОКРВВЕРХ(...) -> ОкруглитьВверх(...).
 3. Тх_Тесты (оба цикла демо-теста, 2 вхождения): выражение -> хелпер;
    граничная семантика потолка независимо закреплена в тестах
    СвояМодельДоступна (1,25 -> 2 хардкод) и ЗамещениеПоШирине (границы).
"""
import pathlib

SRV = pathlib.Path(
    "src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_ТехникаСервер/Ext/Module.bsl")
TST = pathlib.Path(
    "src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_Тесты/Ext/Module.bsl")

HELPER = (
    "// Округляет положительное число вверх до целого (потолок): 1,25 -> 2,\n"
    "// 2,0 -> 2. Глобальной функции потолка в языке нет (есть только Окр/Цел),\n"
    "// семантика design 6.3 «Количество = округление вверх» реализована здесь.\n"
    "//\n"
    "// Параметры:\n"
    "//   Значение - Число - положительное число (смены / (дней x смен в день)).\n"
    "//\n"
    "// Возвращаемое значение:\n"
    "//   Число - минимальное целое, >= Значения.\n"
    "//\n"
    "Функция ОкруглитьВверх(Значение) Экспорт\n"
    "\n"
    "\tЦелаяЧасть = Цел(Значение);\n"
    "\tВозврат ЦелаяЧасть + ?(Значение > ЦелаяЧасть, 1, 0);\n"
    "\n"
    "КонецФункции\n"
    "\n")

def main():
    src = SRV.read_bytes()
    assert src[:3] == b"\xef\xbb\xbf", "SRV BOM expected"
    text = src[3:].decode("utf-8")

    anchor = "// Заполняет документ «Потребность в технике» по потребности техкарт"
    assert text.count(anchor) == 1, "helper insert anchor not unique"
    text = text.replace(anchor, HELPER + anchor)

    old_engine = ("\t\t\tНовСтр.Количество = ОКРВВЕРХ("
                  "НовСтр.ПотребностьСмен / (ДнейПериода * СменВдень));")
    new_engine = ("\t\t\tНовСтр.Количество = ОкруглитьВверх("
                  "НовСтр.ПотребностьСмен / (ДнейПериода * СменВдень));")
    assert text.count(old_engine) == 1, "engine anchor not unique"
    text = text.replace(old_engine, new_engine)
    # докстринги/комментарии: нотация несуществующей функции -> «округление вверх»
    text = text.replace(
        "// Автотранспорт), Количество = ОКРВВЕРХ(ПотребностьСмен / (ДнейПериода x",
        "// Автотранспорт), Количество = округление вверх(ПотребностьСмен / (дней x")
    text = text.replace(
        "// Количество = ОКРВВЕРХ(ПотребностьСмен / (ДнейПериода x СменВдень)).",
        "// Количество = округление вверх(ПотребностьСмен / (дней x СменВдень)).")
    assert text.count("ОКРВВЕРХ") == 0, "no ОКРВВЕРХ mentions may remain in SRV"
    SRV.write_bytes(b"\xef\xbb\xbf" + text.encode("utf-8"))

    src = TST.read_bytes()
    assert src[:3] == b"\xef\xbb\xbf", "TST BOM expected"
    ttext = src[3:].decode("utf-8")

    old_test = ("\t\t\tПроверить(Контекст, "
                "НСтр(\"ru = 'Количество = ОКРВВЕРХ(смен/10)'\"),\n"
                "\t\t\t\tСтр.Количество = ОКРВВЕРХ(Стр.ПотребностьСмен / 10),")
    new_test = ("\t\t\tПроверить(Контекст, "
                "НСтр(\"ru = 'Количество = округление вверх (смен/10)'\"),\n"
                "\t\t\t\tСтр.Количество = "
                "Тх_ТехникаСервер.ОкруглитьВверх(Стр.ПотребностьСмен / 10),")
    assert ttext.count(old_test) == 2, "test anchor expected twice"
    ttext = ttext.replace(old_test, new_test)
    # комментарии: «строка не меняется, Количество = ОКРВВЕРХ(...)» и «ОКРВВЕРХ(25...)»
    ttext = ttext.replace(
        "// строка не меняется, Количество = ОКРВВЕРХ(смен/(дней x смен в день)).",
        "// строка не меняется, Количество = округление вверх(смен/(дней x смен в день)).")
    ttext = ttext.replace(
        "// ОКРВВЕРХ(25 / (10 x 2)) = ОКРВВЕРХ(1,25) = 2.",
        "// округление вверх(25 / (10 x 2)): 1,25 -> 2.")
    assert ttext.count("ОКРВВЕРХ") == 0, "no ОКРВВЕРХ mentions may remain in TST"
    TST.write_bytes(b"\xef\xbb\xbf" + ttext.encode("utf-8"))
    print("OK: t9_fix4 applied (helper ОкруглитьВверх + engine + 2 test sites)")

if __name__ == "__main__":
    main()
