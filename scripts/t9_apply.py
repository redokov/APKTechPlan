def part1_doc(d):
    # ТЧ сегменты по <TabularSection>; ТС ShowError - в 1-й (Осн) и 3-й (Авто).
    import re
    positions = [m.start() for m in re.finditer(r"<TabularSection ", d)]
    assert len(positions) == 3, f"часть 1: ожидалось 3 ТЧ, найдено {len(positions)}"
    seg1 = d[positions[0]:positions[1]]
    seg3 = d[positions[2]:]
    old = "<FillChecking>ShowError</FillChecking>"
    new = "<FillChecking>DontCheck</FillChecking>"
    assert seg1.count(old) == 1 and seg3.count(old) == 1, \
        "часть 1: ТС ShowError не по одному в сегментах Осн/Авто"
    k1 = positions[0] + seg1.find(old)
    k3 = positions[2] + seg3.find(old)
    assert 0 < k1 < k3
    return d[:k1] + new + d[k1 + len(old):k3] + new + d[k3 + len(old):]


