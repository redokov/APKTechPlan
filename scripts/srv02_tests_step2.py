#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""SRV-02 сессия 4, шаг 2: ТестДоступныеМодели_ПланРаспределения (приписки регистра
вместо плана) и ТестДоступныеМодели_БезПлана (пустой срез 31.12.1999)."""
import io
import sys

PATH = r"src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_Тесты/Ext/Module.bsl"


def rep(text, old, new):
    assert text.count(old) == 1, "анкер найден %d раз: %r..." % (text.count(old), old[:60])
    return text.replace(old, new)


def main():
    with io.open(PATH, encoding="utf-8") as f:
        t = f.read()

    # 1) ПланРаспределения: докстринг (упоминание плана)
    t = rep(t, '''// ТС (va_prep_data, модель «Тх_Тест Базовая») и проверяет карту моделей
// подразделения; по «чужому» подразделению - флаг отсутствия плана.''',
'''// ТС (va_prep_data, модель «Тх_Тест Базовая», АпкТипТС = СХТехника),
// приписанных подразделению записями регистра истории ТС
// (Исправно = Истина), и проверяет карту моделей подразделения;
// по «чужому» подразделению - флаг «нет исправных ТС».''')

    # 2) ПланРаспределения: блок плана -> приписки
    t = rep(t, '''\t\t\t\t// План распределения: достаточно ТЧ Подразделения и Техника.
\t\t\t\tДокОбъект = Документы.АпкПланТехническихРесурсов.СоздатьДокумент();
\t\t\t\tДокОбъект.Дата = ТекущаяДатаСеанса();
\t\t\t\tДокОбъект.Организация = Организация;
\t\t\t\tДокОбъект.СценарийПланирования = Сценарий;
\t\t\t\tСтрПодр = ДокОбъект.Подразделения.Добавить();
\t\t\t\tСтрПодр.Подразделение = Подразделение;
\t\t\t\tДля Каждого ТССылка Из ТС Цикл
\t\t\t\t\tСтрТС = ДокОбъект.Техника.Добавить();
\t\t\t\t\tСтрТС.ТранспортноеСредство = ТССылка;
\t\t\t\tКонецЦикла;
\t\t\t\tДокОбъект.Записать(РежимЗаписиДокумента.Проведение);
\t\t\t\tДокСсылка = ДокОбъект.Ссылка;''',
'''\t\t\t\t// Доступность - записи истории ТС (решение владельца
\t\t\t\t// 10.11.2026): приписка тестовых ТС к организации и
\t\t\t\t// подразделению отбора, Исправно = Истина.
\t\t\t\tДля Каждого ТССылка Из ТС Цикл
\t\t\t\t\tЗаписатьПрипискуТС(ТССылка, Организация, Подразделение);
\t\t\t\tКонецЦикла;''')

    # 3) ПланРаспределения: тексты проверок (план -> исправные ТС)
    t = rep(t, '''\t\t\t\tПроверить(Контекст, НСтр("ru = 'план найден (флаг сброшен)'"),''',
'''\t\t\t\tПроверить(Контекст, НСтр("ru = 'исправные ТС есть (флаг сброшен)'"),''')
    t = rep(t, '''\t\t\t\tПроверить(Контекст, НСтр("ru = 'тип ТС = СХТехника (ТЧ Техника)'"),''',
'''\t\t\t\tПроверить(Контекст, НСтр("ru = 'тип ТС = СХТехника (реквизит АпкТипТС)'"),''')
    t = rep(t, '''\t\t\t\tПроверить(Контекст, НСтр("ru = 'чужое подразделение: флаг плана'"),''',
'''\t\t\t\tПроверить(Контекст, НСтр("ru = 'чужое подразделение: флаг отсутствия ТС'"),''')

    # 4) ПланРаспределения: очистка - приписки ТХТС* вместо документа
    t = rep(t, '''\t// Очистка: документ плана распределения и тестовые подразделения.
\tУдалитьСсылку(ДокСсылка);
\tУдалитьСсылку(Подразделение);
\tУдалитьСсылку(ЧужоеПодразделение);''',
'''\t// Очистка: приписки тестовых ТС (записей по ТХТС* в регистре
\t// истории быть не должно, Q-006/К4а) и тестовые подразделения;
\t// сбой очистки - видимый провал теста.
\tОшибкаОчистки = "";
\tВыборкаОчистки = Тх_ТехникаСервер.ВыполнитьЗапросАПК(
\t\t"ВЫБРАТЬ Спр.Ссылка КАК Ссылка
\t\t|ИЗ Справочник.ТранспортныеСредства КАК Спр
\t\t|ГДЕ Спр.Код ПОДОБНО &Шаблон И НЕ Спр.ПометкаУдаления",
\t\tНовый Структура("Шаблон", "ТХТС%")).Выбрать();
\tПока ВыборкаОчистки.Следующий() Цикл
\t\tОшибкаОчистки = ОшибкаОчистки + УдалитьПрипискуТС(ВыборкаОчистки.Ссылка);
\tКонецЦикла;
\tЕсли ОшибкаОчистки <> "" Тогда
\t\tПроверить(Контекст, НСтр("ru = 'восстановление данных после теста'"),
\t\t\tЛожь, ОшибкаОчистки);
\tКонецЕсли;
\tУдалитьСсылку(Подразделение);
\tУдалитьСсылку(ЧужоеПодразделение);''')

    # 5) БезПлана: докстринг + пустой срез 31.12.1999
    t = rep(t, '''// по свежесозданному сценарию нет ни одного документа плана - карта пуста,
// флаг установлен; контракт карты - три колонки.''',
'''// в срезе истории ТС нет ни одной записи (дата среза 31.12.1999 -
// раньше всех демо-записей регистра с 2000-01-01) - карта пуста,
// флаг установлен (новая семантика: «нет исправных ТС в срезе»);
// контракт карты - три колонки.''')
    t = rep(t, '''\t\t\tПараметры = Новый Структура("СценарийПланирования", Сценарий);''',
'''\t\t\t// Дата среза 31.12.1999: срез пуст, карта пуста, флаг установлен.
\t\t\tПараметры = Новый Структура("СценарийПланирования, ДатаНачала",
\t\t\t\tСценарий, Дата(1999, 12, 31));''')

    with io.open(PATH, "w", encoding="utf-8", newline="") as f:
        f.write(t)
    sys.stdout.buffer.write("OK: шаг 2 (карта доступности, 2 теста)\n".encode("utf-8"))


if __name__ == "__main__":
    main()
