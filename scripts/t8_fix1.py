#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T8 fix1: замечания bsl-ls по новому коду.

 1. Пустой блок Исключение (MissingCodeTryCatchEx, Error) в очистке теста
    ТестДоступныеМодели_ПланРаспределения: заменён на переиспользование
    хелпера УдалитьСсылку (generic ПолучитьОбъект().Удалить() работает
    и для документов); докстринг хелпера расширен.
 2. НайтиПоНаименованию (UsingFindElementByString, Warning) в проверке
    модели «Тх_Тест Базовая»: заменён на запрос по Наименование = &Имя.
"""
import pathlib

TST = pathlib.Path(
    "src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_Тесты/Ext/Module.bsl")


def read_bom(p):
    return p.read_bytes()[3:].decode("utf-8")


def write_bom(p, text):
    p.write_bytes(b"\xef\xbb\xbf" + text.encode("utf-8"))


OLD_CLEANUP = """	// Очистка: документ плана распределения и тестовые подразделения.
	Если ДокСсылка <> Неопределено Тогда
		Попытка
			ДокОбъектУдал = ДокСсылка.ПолучитьОбъект();
			Если ДокОбъектУдал <> Неопределено Тогда
				ДокОбъектУдал.Удалить();
			КонецЕсли;
		Исключение
		КонецПопытки;
	КонецЕсли;
	УдалитьСсылку(Подразделение);
	УдалитьСсылку(ЧужоеПодразделение);"""

NEW_CLEANUP = """	// Очистка: документ плана распределения и тестовые подразделения.
	УдалитьСсылку(ДокСсылка);
	УдалитьСсылку(Подразделение);
	УдалитьСсылку(ЧужоеПодразделение);"""

OLD_DOC = """//   Ссылка - СправочникСсылка, Неопределено - ссылка на удаление."""
NEW_DOC = """//   Ссылка - СправочникСсылка, ДокументСсылка, Неопределено -
//            ссылка на удаление (владельцем данных не является)."""

OLD_FIND = """					Проверить(Контекст, НСтр("ru = 'модель = Тх_Тест Базовая'"),
						Стр.МодельТехники = Справочники.АпкМоделиСХТехники
							.НайтиПоНаименованию("Тх_Тест Базовая"));"""

NEW_FIND = """					МодельБазовая = Неопределено;
					ВыборкаМод = Тх_ТехникаСервер.ВыполнитьЗапросАПК(
						"ВЫБРАТЬ ПЕРВЫЕ 1 Спр.Ссылка КАК Ссылка
						|ИЗ Справочник.АпкМоделиСХТехники КАК Спр
						|ГДЕ Спр.Наименование = &Наименование И НЕ Спр.ПометкаУдаления",
						Новый Структура("Наименование", "Тх_Тест Базовая")).Выбрать();
					Если ВыборкаМод.Следующий() Тогда
						МодельБазовая = ВыборкаМод.Ссылка;
					КонецЕсли;
					Проверить(Контекст, НСтр("ru = 'модель = Тх_Тест Базовая'"),
						Стр.МодельТехники = МодельБазовая);"""


def main():
    t = read_bom(TST)
    for old, new, tag in ((OLD_CLEANUP, NEW_CLEANUP, "cleanup"),
                          (OLD_DOC, NEW_DOC, "docstring"),
                          (OLD_FIND, NEW_FIND, "find-by-query")):
        assert t.count(old) == 1, f"якорь {tag} не найден или неоднозначен"
        t = t.replace(old, new)
    write_bom(TST, t)
    print("t8_fix1: cleanup via UdalitySsylku, docstring, find-by-query")


if __name__ == "__main__":
    main()
