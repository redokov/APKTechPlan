def between(text, start, end, new):
    i = text.index(start)
    j = text.index(end, i)
    return text[:i] + new + text[j:]


def rep(text, old, new):
    assert text.count(old) == 1, "анкер найден %d раз: %r..." % (text.count(old), old[:70])
    return text.replace(old, new)


