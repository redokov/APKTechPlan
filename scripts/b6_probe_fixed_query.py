def main():
    c = win32com.client.Dispatch("V85.COMConnector")
    a = c.Connect(
        "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';"
    )
    try:
        q = a.NewObject("Query")
        q.Text = TXT
        scen = a.Справочники.АпкСценарииПланирования.НайтиПоНаименованию(
            "Основной", True
        )
        q.SetParameter("СценарийПланирования", scen)
        q.SetParameter("ДатаНачала", datetime.datetime(2024, 1, 1))
        q.SetParameter("ДатаОкончания", datetime.datetime(2026, 12, 31))
        sel = q.Execute().Choose()
        n = 0
        while sel.Next():
            n += 1
            if n <= 8:
                OUT.write(
                    "  row: Подразделение=%s ВидРаботы=%s Модель=%s Смен=%s\n"
                    % (
                        sel.Подразделение,
                        sel.ВидРаботы,
                        sel.МодельТехники,
                        sel.ПотребностьСмен,
                    )
                )
        OUT.write("FIXED QUERY OK, rows=%d\n" % n)
    except Exception as e:
        try:
            desc = e.excepinfo[2]
        except Exception:
            desc = str(e)
        OUT.write("ERR %s\n" % desc)
    OUT.close()
    print("done")


if __name__ == "__main__":
    main()
