#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Instrument test diagnostics for COM:
- Тх_Тесты: module var collects failure texts; export ДеталиПоследнегоТеста().
- Тх_РаннерТестов: result rows get 4th field 'Детали'.
CRLF+BOM safe.
"""
import io

TESTS = r"src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_Тесты/Ext/Module.bsl"
RUNNER = r"src/cfe/ПланированиеТехникиАПК/DataProcessors/Тх_РаннерТестов/Ext/ObjectModule.bsl"


def load(p):
    raw = open(p, "rb").read()
    return raw.decode("utf-8-sig")


def save(p, text):
    with io.open(p, "wb") as f:
        f.write(b"\xef\xbb\xbf" + text.encode("utf-8"))


# ---- Тх_Тесты ----
t = load(TESTS)

a1 = "#Область Инфраструктура\r\n\r\n// Создаёт контекст теста"
b1 = ("#Область Инфраструктура\r\n\r\n"
      "// Накапливает тексты провальных проверок последнего запущенного теста\r\n"
      "// (для headless-раннеров: COM/Execute не имеют окна сообщений).\r\n"
      "Перем ДеталиПроваловПоследнегоТеста;\r\n\r\n"
      "// Создаёт контекст теста")
assert a1 in t
t = t.replace(a1, b1, 1)

a2 = "\tВозврат Новый Структура(\"Имя, Провалы\", ИмяТеста, Новый Массив);\r\n"
b2 = ("\tДеталиПроваловПоследнегоТеста = Новый Массив;\r\n"
      "\tВозврат Новый Структура(\"Имя, Провалы\", ИмяТеста, Новый Массив);\r\n")
assert a2 in t
t = t.replace(a2, b2, 1)

a3 = "\t\tСтруктураТеста.Провалы.Добавить(ИмяПроверки);\r\n"
b3 = ("\t\tСтруктураТеста.Провалы.Добавить(ИмяПроверки);\r\n"
      "\t\tДеталиПроваловПоследнегоТеста.Добавить(Текст);\r\n")
assert a3 in t
t = t.replace(a3, b3, 1)

a4 = ("// Выводит сообщение SKIP: тест пропущен (нет данных ИБ), считается пройденным.\r\n"
      "//\r\n// Параметры:\r\n//   СтруктураТеста - Структура - контекст теста;\r\n"
      "//   Причина        - Строка - причина пропуска.\r\n//\r\n"
      "Процедура СообщитьПропуск")
b4 = ("// Возвращает накопленные тексты провалов последнего теста\r\n"
      "// (вызывается раннером после каждого теста; для COM-прогонов).\r\n"
      "//\r\n// Возвращаемое значение:\r\n//   Строка - провалы через перевод строки.\r\n//\r\n"
      "Функция ДеталиПоследнегоТеста() Экспорт\r\n\r\n"
      "\tВозврат СтрСоединить(ДеталиПроваловПоследнегоТеста, Символы.ПС);\r\n\r\n"
      "КонецФункции\r\n\r\n"
      "// Выводит сообщение SKIP: тест пропущен (нет данных ИБ), считается пройденным.\r\n"
      "//\r\n// Параметры:\r\n//   СтруктураТеста - Структура - контекст теста;\r\n"
      "//   Причина        - Строка - причина пропуска.\r\n//\r\n"
      "Процедура СообщитьПропуск")
assert a4 in t
t = t.replace(a4, b4, 1)
save(TESTS, t)

# ---- Тх_РаннерТестов ----
r = load(RUNNER)
a5 = ("\tРезультаты.Добавить(Новый Структура(\"Имя, Прошёл, ДлительностьМс\",\r\n"
      "\t\tИмяТеста, Прошёл, Длительность));\r\n")
b5 = ("\tДетали = Тх_Тесты.ДеталиПоследнегоТеста();\r\n"
      "\tРезультаты.Добавить(Новый Структура(\"Имя, Прошёл, ДлительностьМс, Детали\",\r\n"
      "\t\tИмяТеста, Прошёл, Длительность, Детали));\r\n")
assert a5 in r
r = r.replace(a5, b5, 1)
save(RUNNER, r)

print("OK: Тх_Тесты + runner instrumented (ДеталиПоследнегоТеста + поле Детали)")
