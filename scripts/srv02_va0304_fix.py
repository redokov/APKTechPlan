#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""SRV-02: fix feature 03->04 leakage (приписка ТХВА0301 ломит изоляцию среза).
1) фича 04: контекстная очистка распространяется на все Тх_VA% ТС% (вкл. 03);
2) фича 03: финальный teardown - приписки набором пустых записей + удаление ТС."""
import io
import sys

P03 = "tests/vanessa/03-plan-tehresursov-prinyatye-tc.feature"
P04 = "tests/vanessa/04-preduprezhdenie-ts-dva-podrazdeleniya.feature"


def rep(path, old, new):
    s = io.open(path, encoding="utf-8").read()
    assert s.count(old) == 1, (path, s.count(old), old[:60])
    s = s.replace(old, new)
    io.open(path, "w", encoding="utf-8", newline="").write(s)


TEARDOWN = '''
\t# 3. Teardown (Q-006/К4а): приписка тестового ТС убирается набором пустых
\t#    записей, само ТС удаляется - срез 31.12.1999 остаётся чистым для
\t#    следующих сценариев (утечка 03 -> 04 ломила изоляцию уровня 1).
\tИ я выполняю код встроенного языка на сервере
\t|ЗапросТС = Новый Запрос("ВЫБРАТЬ Спр.Ссылка ИЗ Справочник.ТранспортныеСредства КАК Спр ГДЕ Спр.Наименование ПОДОБНО ""Тх_VA_03 ТС%""");|
\t|ВыбТС = ЗапросТС.Выполнить().Выбрать();|
\t|Пока ВыбТС.Следующий() Цикл|
\t|\tНаборИст = РегистрыСведений.АпкИсторияТранспортныхСредств.СоздатьНаборЗаписей();|
\t|\tНаборИст.Отбор.ТранспортноеСредство.Установить(ВыбТС.Ссылка);|
\t|\tНаборИст.Записать(Истина);|
\t|\tВыбТС.Ссылка.ПолучитьОбъект().Удалить();|
\t|КонецЦикла;|
'''


def main():
    # 04: расширенная контекстная очистка (самодостаточность)
    rep(P04,
        '|ЗапросТС = Новый Запрос("ВЫБРАТЬ Спр.Ссылка ИЗ Справочник.ТранспортныеСредства КАК Спр ГДЕ Спр.Наименование ПОДОБНО ""Тх_VA_04 ТС%""");|',
        '|ЗапросТС = Новый Запрос("ВЫБРАТЬ Спр.Ссылка ИЗ Справочник.ТранспортныеСредства КАК Спр ГДЕ Спр.Наименование ПОДОБНО ""Тх_VA% ТС%""");|')
    rep(P04,
        '# записи истории тестовых ТС (Тх_VA_04 ТС% и ТХТС* - чужие приписки',
        '# записи истории тестовых ТС (Тх_VA% ТС% - свои и чужие (03) приписки')

    # 03: teardown в конец файла
    s = io.open(P03, encoding="utf-8").read()
    anchor = '|Сообщить("ТХ_03 строк по модели тестового ТС: " + Строка(ТЗ[0].Н));|'
    assert s.count(anchor) == 1
    s = s.replace(anchor, anchor + "\n" + TEARDOWN.rstrip("\n"))
    io.open(P03, "w", encoding="utf-8", newline="").write(s)

    sys.stdout.buffer.write("OK: 03 teardown + 04 wide cleanup\n".encode("utf-8"))


if __name__ == "__main__":
    main()
