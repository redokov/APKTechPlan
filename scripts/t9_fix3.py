#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T9 fix3 (bsl-ls, третья волна).

MissingParameterDescription в Тх_ТехникаСервер (строки 1152/1232):
звёздочка на ВЕРХНЕМ уровне секции «Параметры:» ломает распознавание
описания (std453). Прецедент модуля: параметры верхнего уровня - без
звёздочки (ЗаполнитьПланРабот, ПотребностьПоТехкартам и др.),
звёздочка легитимна только на вложенном уровне структуры.

 1. ПодобратьЗамещение: «* МодельОригинал/Модели/ТипКандидата» -> без «*».
 2. ЗаполнитьТЧПланаРабот: «* ДокументОбъект» -> без «*»,
    продолжение выровнено под тип (стиль ЗаполнитьПланРабот).
"""
import pathlib

SRV = pathlib.Path(
    "src/cfe/ПланированиеТехникиАПК/CommonModules/Тх_ТехникаСервер/Ext/Module.bsl")

def main():
    src = SRV.read_bytes()
    assert src[:3] == b"\xef\xbb\xbf", "BOM expected"
    text = src[3:].decode("utf-8")

    fixes = [
        # --- ПодобратьЗамещение: три параметра верхнего уровня ---
        ("//   * МодельОригинал - СправочникСсылка - недоступная модель строки;\n"
         "//   * Модели         - ТаблицаЗначений - карта доступности T8;\n"
         "//   * ТипКандидата   - ПеречислениеСсылка.АпкТипыТС - вид кандидатов.",
         "//   МодельОригинал - СправочникСсылка - недоступная модель строки;\n"
         "//   Модели         - ТаблицаЗначений - карта доступности T8;\n"
         "//   ТипКандидата   - ПеречислениеСсылка.АпкТипыТС - вид кандидатов."),
        # --- ЗаполнитьТЧПланаРабот: ДокументОбъект ---
        ("//   * ДокументОбъект - ДокументОбъект.Тх_ПланТехническихРесурсов -\n"
         "//     заполняемый документ;",
         "//   ДокументОбъект - ДокументОбъект.Тх_ПланТехническихРесурсов -\n"
         "//                   заполняемый документ;"),
    ]
    for old, new in fixes:
        assert text.count(old) == 1, "anchor not unique/found: %r" % old[:60]
        text = text.replace(old, new)

    assert "//   * " not in text, "no top-level asterisks must remain"
    SRV.write_bytes(b"\xef\xbb\xbf" + text.encode("utf-8"))
    print("OK: t9_fix3 applied (4 top-level asterisks removed in 2 docstrings)")

if __name__ == "__main__":
    main()
