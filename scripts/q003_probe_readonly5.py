import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
import win32com.client

CONN = "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';"


def q(agent, text):
    r = agent.NewObject("Запрос")
    r.Текст = text
    return r.Выполнить().Выгрузить()


def main():
    agent = win32com.client.Dispatch("V85.COMConnector").Connect(CONN)
    print("connected")
    print("\n== ЕдиницДоступно по модели: как считает код (строки) vs уникальные машины")
    rows = q(agent, """ВЫБРАТЬ
        ТС.АпкМодель.Наименование КАК Модель,
        КОЛИЧЕСТВО(*) КАК Строк,
        КОЛИЧЕСТВО(РАЗЛИЧНЫЕ ТЧ.ТранспортноеСредство) КАК Машин
        ИЗ Документ.АпкПланТехническихРесурсов.Техника КАК ТЧ
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ Справочник.ТранспортныеСредства КАК ТС
            ПО ТС.Ссылка = ТЧ.ТранспортноеСредство
            ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов КАК Д
            ПО Д.Ссылка = ТЧ.Ссылка
        ГДЕ Д.Проведен
        СГРУППИРОВАТЬ ПО ТС.АпкМодель.Наименование
        УПОРЯДОЧИТЬ ПО Модель""")
    for r in rows:
        flag = "  <-- ДУБЛЬ" if r.Строк != r.Машин else ""
        print("   %-34s строк=%-3s машин=%-3s%s" % (str(r.Модель)[:34], r.Строк, r.Машин, flag))

    print("\n== Строки регистра дефицита по этой модели (что записал последний расчёт)")
    try:
        for r in q(agent, """ВЫБРАТЬ
                Р.МодельТехники.Наименование КАК Модель,
                Р.Подразделение.Наименование КАК Подр,
                Р.ПериодНачала КАК Начало, Р.ПериодОкончания КАК Окончание,
                Р.ПотребностьСмен КАК Потр, Р.ДоступноСмен КАК Доступно,
                Р.НехватаетСмен КАК Дефицит
                ИЗ РегистрСведений.Тх_ДефицитТехники КАК Р
                УПОРЯДОЧИТЬ ПО Р.МодельТехники.Наименование"""):
            print("   %-28s %-14s %s..%s потр=%-6s дост=%-6s деф=%s" % (
                str(r.Модель)[:28], str(r.Подр)[:14], str(r.Начало)[:10], str(r.Окончание)[:10],
                round(r.Потр, 2), round(r.Доступно, 2), round(r.Дефицит, 2)))
    except Exception as e:
        print("   ошибка:", e)


if __name__ == "__main__":
    main()
