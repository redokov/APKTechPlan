#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Probe: cold-run of feature 08 server blocks 4/6 (exact inline code paths) via COM."""
import sys
import win32com.client

conn = win32com.client.Dispatch("V85.COMConnector").Connect(
    "Srvr='localhost';Ref='dev_erpapk_demo';Usr='Администратор (ОрловАВ)';Pwd='';")

def out(s):
    sys.stdout.buffer.write((s + "\n").encode("utf-8"))

# === replicate Context setup ===
m = conn.Справочники.АпкМоделиСХТехники.НайтиПоНаименованию("Тх_Тест Базовая")
ob = m.ПолучитьОбъект(); ob.КоэффициентПереводаВУЭГА = 6; ob.Записать()
out("setup: КУЭГА=6")

S = conn.NewObject("Структура")
S.Вставить("СценарийПланирования", conn.Справочники.АпкСценарииПланирования.НайтиПоНаименованию("Основной"))
S.Вставить("Организация", conn.Справочники.Организации.НайтиПоНаименованию("НИВА"))
S.Вставить("Подразделение", conn.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Отделение №2"))
q = conn.NewObject("Запрос"); q.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2014, 1, 1) КАК Д"
v = q.Выполнить().Выбрать(); v.Следующий(); S.Вставить("ДатаНачала", v.Д)
q = conn.NewObject("Запрос"); q.Текст = "ВЫБРАТЬ ДАТАВРЕМЯ(2015, 12, 31) КАК Д"
v = q.Выполнить().Выбрать(); v.Следующий(); S.Вставить("ДатаОкончания", v.Д)
S.Вставить("ДнейПериода", 10)
S.Вставить("СменВдень", 1)

Doc = conn.Документы.АпкПланТехническихРесурсов.СоздатьДокумент()
Doc.Дата = conn.ТекущаяДатаСеанса()
Sv = conn.Тх_ТехникаСервер.ЗаполнитьПланРабот(Doc, S)
out("formation: строк=%s замещ=%s" % (Sv.КоличествоСтрок, Sv.ЗамещенныхСтрок))
Doc.ПредставлениеПодразделений = "Тх_VA_ПланРабот"
Doc.Записать()
out("doc written: %s" % Doc.Ссылка)

# === block 4 (exact query from feature) ===
q4 = conn.NewObject("Запрос")
q4.Текст = ("ВЫБРАТЬ С.Ссылка ИЗ Документ.АпкПланТехническихРесурсов КАК С "
            "ВНУТРЕННЕЕ СОЕДИНЕНИЕ Документ.АпкПланТехническихРесурсов.Подразделения КАК П "
            "ПО С.Ссылка = П.Ссылка "
            "ГДЕ НЕ С.Проведен И С.СценарийПланирования = &Сцен И С.Организация = &Орг "
            "И П.Подразделение = &Подр УПОРЯДОЧИТЬ ПО С.Дата УБЫВ")
q4.УстановитьПараметр("Сцен", conn.Справочники.АпкСценарииПланирования.НайтиПоНаименованию("Основной"))
q4.УстановитьПараметр("Орг", conn.Справочники.Организации.НайтиПоНаименованию("НИВА"))
q4.УстановитьПараметр("Подр", conn.Справочники.СтруктураПредприятия.НайтиПоНаименованию("Отделение №2"))
ТЗ = q4.Выполнить().Выгрузить()
out("block4: docs=%d" % ТЗ.Количество())
ДокСсылка = ТЗ.Получить(0).Ссылка
out("block4: Подр.строк=%d [0]=%s" % (ДокСсылка.Подразделения.Количество(),
    ДокСсылка.Подразделения.Получить(0).Подразделение.Наименование))
ВсегоСтрок = (ДокСсылка.Техника.Количество() + ДокСсылка.Оборудование.Количество()
              + ДокСсылка.Автотранспорт.Количество() + ДокСсылка.Прицепы.Количество())
out("block4: ВсегоСтрок=%d" % ВсегоСтрок)
ЕстьЗамещение = False
for i in range(ДокСсылка.Техника.Количество()):
    СтрТС = ДокСсылка.Техника.Получить(i)
    if not СтрТС.ТранспортноеСредство.Код:
        raise SystemExit("пустая строка ТС")
    if СтрТС.ТранспортноеСредство.Код.find("ТХТС") == 0:
        ЕстьЗамещение = True
out("block4: ЕстьЗамещение=%s" % ЕстьЗамещение)

# === block 6 (exact query) ===
q6 = conn.NewObject("Запрос")
q6.Текст = ("ВЫБРАТЬ С.Ссылка ИЗ Документ.АпкПланТехническихРесурсов КАК С "
            "ГДЕ С.ПредставлениеПодразделений = &М")
q6.УстановитьПараметр("М", "Тх_VA_ПланРабот")
ТЗ6 = q6.Выполнить().Выгрузить()
out("block6: marker docs=%d (need 1)" % ТЗ6.Количество())
Д6 = ТЗ6.Получить(0).Ссылка
out("block6: Проведен=%s Подр=%d Тех=%d" % (Д6.Проведен, Д6.Подразделения.Количество(), Д6.Техника.Количество()))

# === cleanup probe artifacts (delete marker doc + restore КУЭГА) ===
Д6.ПолучитьОбъект().Удалить()
out("probe doc deleted")
ob2 = m.ПолучитьОбъект(); ob2.КоэффициентПереводаВУЭГА = 0; ob2.Записать()
out("КУЭГА restored")
